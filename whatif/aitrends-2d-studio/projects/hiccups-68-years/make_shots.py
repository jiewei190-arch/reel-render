"""Build story/shots.json from timeline/words.json: each shot starts at a spoken word (script-aligned Whisper timings).
Usage: python3 make_shots.py   (run after tools/transcribe.py). Prints every shot length (target ~1.0-2.7 s)."""
import json, os, re
D = os.path.dirname(os.path.abspath(__file__))
W = json.load(open(f'{D}/timeline/words.json')); W = W.get('words', W) if isinstance(W, dict) else W
norm = lambda w: re.sub(r"[^\w'%]", '', w.lower())
TAIL, LEAD = 0.5, 0.06

def t_of(word, nth=1, after=0.0):
    hits = [w for w in W if w['start'] >= after - 0.01 and (norm(w['word']) == norm(word[1:]) if word.startswith('=') else norm(w['word']).startswith(norm(word)))]
    if len(hits) < nth: raise SystemExit(f'word {word!r} #{nth} not found after {after}')
    return hits[nth - 1]['start']

S = lambda at, name, gain=-12, **k: {'at': at, 'name': f'toon3d:{name}', 'gain': gain, **k}
Wd = lambda word, name, gain=-12, **k: {'word': word, 'name': f'toon3d:{name}', 'gain': gain, **k}
# (id, start word, nth, extra offset, scene note, transition, sfx)
SHOTS = [
    ('s01', None, 1, 0, 'FRAME 1: the farmer mid-hic in his farmyard + 2-line top caption', None, [S(0.1, 'sparkle', -18)]),
    ('s02', 'straight', 1, -0.5, 'close-up deadpan stare, 68 YEARS', {'type': 'cut'}, [Wd('straight', 'stamp', -14)]),
    ('s03', 'in', 1, 0, 'the farmer and a very large hog, 1922, CHARLES OSBORNE', {'type': 'whipBlur', 'dir': 1}, [S(0, 'swoosh', -14), S(0.05, 'stamp', -12), Wd('osborne', 'pop', -12)]),
    ('s04', 'under', 1, 0, 'the hog topples onto him: dust cloud, hat flies, 350-POUND HOG', {'type': 'cut'}, [S(0.3, 'slide', -12), S(0.45, 'thud', -6), S(0.5, 'boing', -12), Wd('350', 'pop', -14)]),
    ('s05', 'then', 1, 0, 'back on his feet: the first HIC!, he double-takes at himself', {'type': 'whipBlur', 'dir': -1}, [S(0, 'swoosh', -14)]),
    ('s06', 'and', 1, 0, 'side-on, hics keep coming; stare at the lens on "stop"', {'type': 'cut'}, [Wd('stop', 'stamp', -12)]),
    ('s07', 'according', 1, 0, 'INSERT 1: ACCORDING TO GUINNESS 20-40 HICCUPS A MINUTE', {'type': 'flash'}, [S(0, 'impact', -10), S(0.05, 'whoosh', -12)]),
    ('s08', 'day', 1, 0, 'clock spins, day/night flicker over the yard, FOR DECADES', {'type': 'whipBlur', 'dir': 1}, [S(0, 'clock', -12), Wd('decades', 'pop', -12)]),
    ('s09', 'doctors', 1, 0, "doctor's office: the doctor leans in, HIC!, he jumps; shrugs", {'type': 'iris'}, [S(0, 'door', -16), Wd('nothing', 'fail', -14)]),
    ('s10', 'his', 1, 0, 'stopwatch to 50:00 while he smiles... then HIC!', {'type': 'whipBlur', 'dir': -1}, [S(0, 'swoosh', -14), S(0.2, 'tick', -14), S(0.7, 'tick', -14), Wd('hours', 'ding', -12)]),
    ('s11', 'but', 1, 0, 'BUT... beat, vignette', {'type': 'cut'}, [S(0, 'suspense', -14), S(0.05, 'stamp', -14)]),
    ('s12', '=he', 1, 0, 'waving hello, NORMAL LIFE', {'type': 'whipBlur', 'dir': 1}, [S(0, 'swoosh', -14), Wd('normal', 'success', -14)]),
    ('s13', '=he', 2, 0, 'wedding: he hics mid-vows, she does not blink; MARRIED x2', {'type': 'cut'}, [S(0, 'bell', -12), Wd('twice', 'pop', -12)]),
    ('s14', '=and', 1, 0, '8 kids; he hics and all eight jump', {'type': 'whipBlur', 'dir': -1}, [S(0, 'swoosh', -14), Wd('eight', 'pop', -12)]),
    ('s15', 'one', 1, 0, "the doctor's theory: chin in hand, ???", {'type': 'iris'}, [S(0.2, 'boing', -14)]),
    ('s16', 'lifting', 1, 0, 'card: cartoon brain, one tiny pop!', {'type': 'cut'}, [S(0, 'impact', -12), Wd('popped', 'pop', -8), Wd('tiny', 'squeak', -14)]),
    ('s17', 'guinness', 1, 0, 'gold record trophy rattles on his hic; WORLD RECORD', {'type': 'whipBlur', 'dir': 1}, [S(0, 'whoosh', -12), Wd('longest', 'stamp', -12), Wd('longest', 'chime', -14, offset=0.1)]),
    ('s18', 'over', 1, 0, 'INSERT 2: counter 400,000,000+ HICCUPS', {'type': 'cut'}, [S(0, 'impact', -10), S(0.05, 'whoosh', -12), S(0.2, 'riser', -16)]),
    ('s19', 'then', 1, 0, '1990: he shuts his eyes and braces', {'type': 'flash'}, [S(0.05, 'stamp', -12), S(0.1, 'suspense', -16)]),
    ('s20', 'they', 1, 0, 'PAYOFF: silence where the hic should be; one eye opens, ?, then a grin; STOPPED.', {'type': 'cut'}, [Wd('stopped', 'stamp', -12), S(9, 'success', -12)]),
    ('s21', 'subscribe', 1, 0, 'closer: back to frame 1 framing (loop)', {'type': 'cut'}, [S(0.05, 'sparkle', -16)]),
]
# hic times: one at 0.05 s (frame 1), then in silent gaps >= 0.34 s between words (centred, >= 1.5 s apart), never after "stopped"
STOP = t_of('1990', 1, 0.0)   # line 9 onward: no more hics (the payoff is the silence)
hics, last = [0.05], 0.05
for a, b in zip(W, W[1:]):
    g = b['start'] - a['end']; m = a['end'] + min(0.14, g / 2 - 0.08)
    if g >= 0.34 and m - last >= 1.5 and m < STOP - 0.6: hics.append(round(m, 3)); last = m
open(f'{D}/scenes/_hics.js', 'w').write('// generated by make_shots.py: global times (s) of every synthesized "hic" (sfx/hic*.wav)\nexport const HICS = ' + json.dumps(hics) + ';\n')

dur = round(W[-1]['end'] + TAIL, 3)
starts, prev = [], 0.0
for sid, word, nth, off, *_ in SHOTS:
    t = 0.0 if word is None else t_of(word, nth, prev) - LEAD + off
    starts.append(round(max(0.0, t), 3)); prev = t + 0.05 - off
out = []
for i, (sid, word, nth, off, scene, tr, sfx) in enumerate(SHOTS):
    st, en = starts[i], (starts[i + 1] if i + 1 < len(SHOTS) else dur)
    line = ' '.join(w['word'] for w in W if st - 0.01 <= w['start'] < en - 0.01)
    sfx = [x if x.get('at', 0) < 9 else {**x, 'at': round(en - st - 0.7, 3)} for x in sfx]
    sfx += [{'at': round(h - st, 3), 'name': f'sfx/hic{"2" if k % 3 == 2 else ""}.wav', 'gain': -4} for k, h in enumerate(hics) if st <= h < en]
    sh = {'id': sid, 'start': st, 'end': round(en, 3), 'line': line, 'scene': scene}
    if tr: sh['in'] = tr
    sh['sfx'] = sfx; out.append(sh)
json.dump({'duration': dur, 'generated_from': 'make_shots.py + timeline/words.json', 'hics': hics, 'shots': out}, open(f'{D}/story/shots.json', 'w'), indent=1)
cfg = json.load(open(f'{D}/config.json')); cfg['duration'] = dur; json.dump(cfg, open(f'{D}/config.json', 'w'), indent=1)
print(f'duration {dur:.2f} s, {len(out)} shots, {len(hics)} hics: {hics}')
for s in out:
    d = s['end'] - s['start']; print(f"  {s['id']}  {s['start']:6.2f}-{s['end']:6.2f}  {d:4.2f}s  {s['line'][:62]}{'   <-- check' if not 0.9 <= d <= 2.8 else ''}")
