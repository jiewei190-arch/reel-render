// law_build.mjs: a law3d recipe ("kit": "law3d") -> a Remotion composition, then the clip QA and the frame-0 gate.
//   node tools/law_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>] [--qa-sample N]
//   (node tools/recipe_build.mjs <slug> forwards here when recipe.json says "kit": "law3d")
// LONG-FORM ("format": "landscape", LONGFORM.md, KIT_LAW3D.md "Long-form (landscape)"): the recipe may live in
// finance/longform/<slug>; the clip QA checks every Nth output frame (--qa-sample N, no sub-frames: no motion blur), the
// shared long-form gate (tools/kit_long.mjs) replaces the Shorts frame-0 gate, and <dir>/chapters.txt is written.
// Shorts keep the full QA (every frame x 4 sub-frames) and the law3d frame-0 gate, unchanged.
// Reads   <shorts>/<slug>/recipe.json + vo/timings.json
// Writes  src/law/gen/<slug_>.law.gen.ts      the recipe + word timings as a TS module
//         src/law/registry.gen.ts             every *.law.gen.ts (LawRoot registers <Pascal>Recipe)
//         out/tmp/<slug>.cues.json            the audio plan (STORY_CUES=<file> python tools/story_mix.py ...)
//         <shorts>/<slug>/RECIPE_QA.md        the QA + gate report
// Nothing here touches the Block Money or tech3d registries.
import { build } from "esbuild";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { chaptersTxt, kitArgs, kitLongGate, kitLongReport, qaTimes } from "./kit_long.mjs";
import { runFraming } from "./framing_kits.mjs";
import { polishQA } from "./polish_qa.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const main = async (argv) => {
  const T0 = Date.now();
  const ka = kitArgs(argv);
  if (ka.err) { console.error(ka.err === "usage" ? "usage: node tools/law_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>] [--qa-sample N]" : ka.err); return 2; }
  const { slug, SHORTS, dir, check, noQa, qaSample, qaSampleGiven } = ka;
  const recipe = JSON.parse(readFileSync(join(dir, "recipe.json"), "utf8"));
  const timings = JSON.parse(readFileSync(join(dir, "vo/timings.json"), "utf8"));
  if (recipe.slug !== slug) { console.error(`recipe.slug "${recipe.slug}" != folder "${slug}"`); return 2; }
  if (recipe.kit !== "law3d") { console.error(`recipe.kit is "${recipe.kit}", not "law3d": use tools/recipe_build.mjs`); return 2; }
  const LS = recipe.format === "landscape";
  const srcRel = SHORTS === resolve(ROOT, "../longform") ? "finance/longform" : "finance/shorts";

  // ---------------------------------------------------------------- 1) codegen
  const wf = (f, txt) => { if (!check) writeFileSync(f, txt); };
  const us = slug.replace(/-/g, "_");
  const pascal = slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("") + "Recipe";
  const words = timings.turns.flatMap((tn) => tn.words.map((w) => ({ w: w.w, turn: tn.turn, t: w.t, end: w.end })));
  const vo = timings.source?.duration;
  mkdirSync(join(ROOT, "src/law/gen"), { recursive: true });
  wf(join(ROOT, `src/law/gen/${us}.law.gen.ts`),
    `// generated by tools/law_build.mjs from ${srcRel}/${slug}/recipe.json + vo/timings.json; do not edit\n` +
    `import type { Word } from "../../fin/recipe/types";\nimport type { LawRecipe } from "../types";\n\n` +
    `export const ID = ${JSON.stringify(pascal)};\nexport const VO_DURATION: number | undefined = ${vo === undefined ? "undefined" : vo};\n` +
    `export const RECIPE: LawRecipe = ${JSON.stringify(recipe, null, 1)};\n` +
    `export const WORDS: Word[] = ${JSON.stringify(words)};\n`);
  const gens = check ? [] : readdirSync(join(ROOT, "src/law/gen")).filter((f) => f.endsWith(".law.gen.ts")).sort();
  wf(join(ROOT, "src/law/registry.gen.ts"),
    `// generated by tools/law_build.mjs; do not edit (lists src/law/gen/*.law.gen.ts)\nimport type { Word } from "../fin/recipe/types";\nimport type { LawRecipe } from "./types";\n` +
    gens.map((f, i) => `import * as L${i} from "./gen/${f.replace(/\.ts$/, "")}";`).join("\n") +
    `\n\nexport const LAW_RECIPES: { id: string; recipe: LawRecipe; words: Word[]; vo?: number }[] = [\n` +
    gens.map((_, i) => `  { id: L${i}.ID, recipe: L${i}.RECIPE, words: L${i}.WORDS, vo: L${i}.VO_DURATION },`).join("\n") + `\n];\n`);
  if (!check) console.log(`wrote src/law/gen/${us}.law.gen.ts and the law registry (${gens.length} recipe(s)); composition ${pascal} in src/index.law.ts`);

  // ---------------------------------------------------------------- 2) compile in node
  const stub = { name: "stub", setup(b) {
    b.onResolve({ filter: /^(remotion|@remotion\/.*|@react-three\/.*)$/ }, (a) => ({ path: a.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "const P=new Proxy(function(){return P},{get:(t,k)=>k==='__esModule'?false:P,apply:()=>P,construct:()=>P}); module.exports=P;", loader: "js" }));
  } };
  const r = await build({ entryPoints: [join(ROOT, "tools/law_entry.ts")], bundle: true, write: false, format: "esm", platform: "node", plugins: [stub], jsx: "automatic", logLevel: "error" });
  mkdirSync(join(ROOT, "out/tmp"), { recursive: true });
  const bundleF = join(ROOT, "out/tmp/law_build.bundle.mjs");
  writeFileSync(bundleF, r.outputFiles[0].text);
  const m = await import(pathToFileURL(bundleF).href + "?" + Date.now());
  let C;
  const Tc = Date.now();
  try { C = m.compileLaw(recipe, words, vo); } catch (e) { console.error(`COMPILE ERROR: ${e.message}`); return 1; }
  const compileS = (Date.now() - Tc) / 1000;
  const L = C.layout;
  const dur = C.duration / 30;
  writeFileSync(join(ROOT, `out/tmp/${slug}.cues.json`), JSON.stringify({ [pascal]: { music: C.audio.music, musicDb: -12, cues: C.audio.cues, duration: dur, cuts: C.shots.map((s) => s.a) } }));
  console.log(`compiled ${C.shots.length} shots, ${dur.toFixed(2)} s (${C.duration} frames, ${L.W}x${L.H}), ${C.audio.cues.length} sfx cues`);
  if (noQa) return 0;
  if (LS) return longForm({ m, C, recipe, words, dur, slug, pascal, dir, check, qaSample, T0, compileS });
  if (qaSampleGiven) console.log("--qa-sample is for long-form only: a Short always gets the full QA (every frame x 4 sub-frames)");

  // ---------------------------------------------------------------- 3) clip QA (every frame x 4 sub-frames)
  const ov = (p, a) => [0, 1, 2].every((k) => Math.abs(p.c[k] - a.c[k]) < p.h[k] + a.h[k]);
  const hits = new Map();
  const note = (k, t) => { if (!hits.has(k)) hits.set(k, t); };
  for (let f = 0; f < C.duration * 4; f++) {
    const t = f / 120;
    const { figs, props } = C.qa(t);
    const sid = C.shotAt(t).id;
    for (const b of figs) {
      if (b.c[1] - b.h[1] < -0.02) note(`${sid} ${b.name} below the floor`, t);
      for (const p of props) if (ov(p, b)) note(`${sid} ${p.name} x ${b.name}`, t);
    }
    const bodies = figs.filter((b) => b.name.endsWith(".body") || b.name.endsWith(".head"));
    for (let i = 0; i < bodies.length; i++) for (let j = i + 1; j < bodies.length; j++) if (bodies[i].name.split(".")[0] !== bodies[j].name.split(".")[0] && ov(bodies[i], bodies[j])) note(`${sid} ${bodies[i].name} x ${bodies[j].name}`, t);
  }
  const qaLines = [...hits].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(3)} s (frame ${Math.floor(t * 30)})`);

  // ---------------------------------------------------------------- 4) gate
  const sub3 = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
  const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
  const crs = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
  const nrm = (a) => { const l = Math.hypot(...a) || 1; return a.map((x) => x / l); };
  const coverage = (cam, b) => {
    const f = nrm(sub3(cam.look, cam.pos)), rgt = nrm(crs(f, [0, 1, 0])), up = crs(rgt, f), th = Math.tan((cam.fov * Math.PI) / 360), asp = L.W / L.H;
    let y0 = Infinity, y1 = -Infinity, x0 = Infinity, x1 = -Infinity;
    for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) {
      const p = [b.c[0] + sx * b.h[0], b.c[1] + sy * b.h[1], b.c[2] + sz * b.h[2]];
      const d = sub3(p, cam.pos), z = dot(d, f);
      if (z <= 0.05) return 0;
      const ny = dot(d, up) / (z * th), nx = dot(d, rgt) / (z * th * asp);
      y0 = Math.min(y0, ny); y1 = Math.max(y1, ny); x0 = Math.min(x0, nx); x1 = Math.max(x1, nx);
    }
    if (x1 < -1 || x0 > 1) return 0;
    return Math.max(0, Math.min(1, y1) - Math.max(-1, y0)) / 2;
  };
  const cam0 = C.camAt(0);
  const subjects = [];
  // a person = the upper body (hip to the top of the head); a prop = its box
  for (const st of C.figsAt(0)) { const bx = m.figBoxes(st); const head = bx.find((b) => b.name.endsWith(".head")), body = bx.find((b) => b.name.endsWith(".body")); const top = head.c[1] + head.h[1], bot = body.c[1]; subjects.push({ name: st.id, person: true, c: [head.c[0], (top + bot) / 2, head.c[2]], h: [0.24 * st.s, (top - bot) / 2, 0.15 * st.s] }); }
  for (const p of C.shotAt(0).props) { const pl = p.place(0), bx = m.KIT_BOX[p.spec.kit]; subjects.push({ name: p.key, c: [pl.p[0] + bx.c[0] * pl.s, pl.p[1] + bx.c[1] * pl.s, pl.p[2] + bx.c[2] * pl.s], h: bx.h.map((v) => v * pl.s) }); }
  const covs = subjects.map((b) => ({ name: b.name, person: !!b.person, k: coverage(cam0, b) })).sort((a, b) => b.k - a.k);
  const best = covs[0] ?? { name: "nothing", k: 0 };
  const hookText = recipe.hook.text;
  const hookWords = hookText.replace(/\*/g, "").trim().split(/\s+/).length;
  const hb = m.hookBox(L, hookText);
  const gold = hookText.match(/\*[^*]+\*/g) ?? [];
  const Q = /\?|^(how|why|what|where|when|who|which)\b|\d|\$/i;
  let stakeAt = null;
  for (let f = 0; f <= 15 && stakeAt === null; f++) if (C.textsAt(f / 30).some((s) => Q.test(s))) stakeAt = f / 30;
  const face0 = new Map(C.figsAt(0).map((b) => [b.id, b.face]));
  let faceAt = null;
  for (let f = 1; f <= 45 && faceAt === null; f++) for (const b of C.figsAt(f / 30)) if (!face0.has(b.id) || face0.get(b.id) !== b.face) { faceAt = f / 30; break; }
  const PUNCH = /^(impact|drop|crash|boom|thud|punch|stamp|coins|scratch|paper|rip|gavel)/;
  const sfx0 = C.audio.cues.filter((c) => c.t <= 0.02);
  const moves = new Set();
  for (const s of C.shots) { if (s.a > 0 && s.a <= 3.0) moves.add(`cut ${s.a.toFixed(2)}`); for (const [t] of s.kicks) if (t <= 3.0 && t > 0.05) moves.add(`hit ${t.toFixed(2)}`); }
  const early = C.shots.filter((s) => s.a < 1.0);
  const whoAt0 = covs.filter((c) => c.person && c.k >= 0.15), whatAt0 = covs.filter((c) => !c.person && c.k >= 0.03);
  const band = [L.capCentre - L.capHalf, L.capCentre + L.capHalf];
  let capT = 0, capOk = 0;
  const capBad = new Set(), cardFace = new Set(), cardBand = new Set(), hookFace = new Set(), cardCard = new Set(), staticF = [];
  const faceRect = (cam, st) => { const f = m.figFace(st); const q = m.project(cam, f.c, L); if (!q || q.x < -100 || q.x > L.W + 100) return null; const r = f.r * q.k; return { x: q.x, y: q.y, w: 2 * r, h: 2 * r }; };
  const hitR = (a, b) => Math.abs(a.x - b.x) * 2 < a.w + b.w && Math.abs(a.y - b.y) * 2 < a.h + b.h;
  let prevCam = null;
  for (let f = 0; f < C.duration; f++) {
    const t = f / 30, s = C.shotAt(t), cam = C.camAt(t);
    if (prevCam && C.shotAt((f - 1) / 30) === s) {
      const d = Math.hypot(...sub3(cam.pos, prevCam.pos)) + Math.hypot(...sub3(cam.look, prevCam.look)) + Math.abs(cam.fov - prevCam.fov) * 0.01 + Math.abs((cam.roll ?? 0) - (prevCam.roll ?? 0)) * 0.01;
      if (d < 2e-4) staticF.push(f);
    }
    prevCam = cam;
    const faces = C.figsAt(t).filter((st) => st.spec.role !== "juror").map((st) => faceRect(cam, st)).filter(Boolean);
    const capOn = t >= 1.0 && recipe.captions !== "off" && s.spec.caption !== "off";
    if (capOn) { capT++; if (faces.every((r) => r.y + r.h / 2 < band[0] || r.y - r.h / 2 > band[1])) capOk++; else capBad.add(s.id); }
    const ds = C.devicesAt(t).filter((d) => d.u >= 0.3);
    for (const d of ds) {
      if (faces.some((r) => hitR(d, r))) cardFace.add(`${d.kind} ${d.text ?? d.title ?? ""}@${t.toFixed(1)}s`.trim());
      if (d.kind !== "verdict" && d.kind !== "caseCard" && d.y + d.h / 2 > band[0] - 1) cardBand.add(`${d.kind} ${d.text ?? d.title ?? ""}`);
    }
    for (let i = 0; i < ds.length; i++) for (let j = i + 1; j < ds.length; j++) if (hitR(ds[i], ds[j])) cardCard.add(`${ds[i].kind}/${ds[j].kind}@${t.toFixed(1)}s`);
    if (t <= C.hookUntil || (C.hookAgain !== null && t >= C.hookAgain)) {
      for (const r of faces) if (hitR(hb, r)) hookFace.add(`${s.id}@${t.toFixed(1)}s`);
      for (const d of ds) if (hitR(hb, d)) cardCard.add(`hook/${d.kind}@${t.toFixed(1)}s`);
    }
  }
  const capShare = capT ? capOk / capT : 1;
  const allActs = C.shots.flatMap((s) => (s.spec.actions ?? []).map((a) => a.do));
  const firstCut = C.shots.length > 1 ? C.shots[1].a : dur;
  const lastShot = C.shots[C.shots.length - 1], firstShot = C.shots[0];
  const loopy = C.hookAgain !== null && JSON.stringify(lastShot.spec.cam.target) === JSON.stringify(firstShot.spec.cam.target);
  const fmt = recipe.format ?? "short";
  const lenOk = fmt === "short" ? dur >= 30 && dur <= 55 : dur >= 300 && dur <= 480;
  // framing QA (screen space, tools/framing_qa.mjs + framing_kits.mjs): heads vs boards/cards, the subject in frame,
  // cards inside the frame, text contrast and size, frame-0 face (RECIPE_GUIDE.md "Framing rules", KIT_*.md)
  const KF = runFraming("law3d", C, m, recipe);
  const gate = [
    ["frame 0 is close: a subject covers >= 50 % of the frame height", best.k >= 0.5, `${best.name} ${(best.k * 100).toFixed(0)} %`, true],
    ["hook at frame 0: <= 5 words, <= 2 lines that fit, exactly one *gold* word", C.hookUntil > 0 && hookWords <= 5 && hb.lines.length <= 2 && hb.textW <= L.hookMaxW && gold.length === 1, `"${hookText}" (${hookWords} words, ${hb.lines.length} line(s), widest ~${hb.textW.toFixed(0)} px, gold: ${gold.join(" ") || "none"}, until ${C.hookUntil.toFixed(2)} s)`, true],
    ["who + what at frame 0 (a person >= 15 % and a prop in view)", whoAt0.length > 0 && whatAt0.length > 0, `who: ${whoAt0.map((c) => c.name).join(", ") || "none"}; what: ${whatAt0.map((c) => c.name).join(", ") || "none"}`, true],
    ["the stake (a number, $ or a question) on screen by 0.5 s", stakeAt !== null, stakeAt === null ? "none by 0.5 s" : `at ${stakeAt.toFixed(2)} s`, true],
    ["first spoken word by 0.2 s", words[0].t <= 0.2, `${words[0].w} at ${words[0].t.toFixed(2)} s`, true],
    ["a sound punch at 0.00 s", sfx0.some((c) => PUNCH.test(c.sfx)), sfx0.map((c) => c.sfx).join(", ") || "none", true],
    ["2-3 cuts or big moves in the first 3 s", moves.size >= 2, [...moves].join(", ") || "none", true],
    ["music + an SFX at frame 0", !!C.audio.music && C.audio.cues.some((c) => c.t <= 0.05), `${C.audio.music}, ${C.audio.cues.filter((c) => c.t <= 0.05).map((c) => c.sfx).join(", ")}`, true],
    ["a face changes by 1.5 s", faceAt !== null, faceAt === null ? "no expression change by 1.5 s" : `at ${faceAt.toFixed(2)} s`, true],
    ["no wide shot in the first 1 s", early.every((s) => s.spec.cam.preset !== "wide"), early.map((s) => `${s.id} ${s.spec.cam.preset}`).join(", "), true],
    ["frame-0 shot cuts away by ~1.0 s (first cut <= 1.25 s)", firstCut <= 1.25, `first cut at ${firstCut.toFixed(2)} s`, true],
    ["faces clear of the caption band on >= 90 % of caption time", capShare >= 0.9, `${(capShare * 100).toFixed(0)} %${capBad.size ? `; a face in the band in ${[...capBad].join(", ")}` : ""}`, true],
    ["text off faces: no device card over a face", cardFace.size === 0, [...cardFace].slice(0, 6).join(", ") || "none", true],
    ["the hook card never covers a face", hookFace.size === 0, [...hookFace].slice(0, 6).join(", ") || "clear", true],
    ["cards never overlap each other or the hook", cardCard.size === 0, [...cardCard].slice(0, 6).join(", ") || "none", true],
    ["tags and counters above the caption band", cardBand.size === 0, [...cardBand].join(", ") || "all above", true],
    ["no static frames: the camera moves on every frame", staticF.length === 0, staticF.length ? `${staticF.length} still frame(s), first ${staticF.slice(0, 5).join(", ")}` : "moves on every frame", true],
    ["story devices: a case-file card, an exhibit and a verdict", ["caseCard", "exhibit", "verdict"].every((k) => allActs.includes(k)), [...new Set(allActs)].join(", ") || "none", false],
    ["loop ending: the hook comes back and the last shot frames the first shot's subject", loopy, `hook again ${C.hookAgain === null ? "not set" : `at ${C.hookAgain.toFixed(2)} s`}; last target ${JSON.stringify(lastShot.spec.cam.target)}`, false],
    [fmt === "short" ? "length 30-55 s" : "length 5-8 min", lenOk, `${dur.toFixed(2)} s`, false],
  ];
  gate.push(...KF.rows);
  // polish rules P1-P4 (tools/polish_qa.mjs): counters land and hold, text fits, no set piece over a featured face
  const PQ = polishQA({ kit: "law3d", C, m, recipe, words });
  gate.push(...PQ.rows);
  const hardFail = gate.some((g) => g[3] && !g[1]);
  const rep = [
    `# ${slug}: law3d recipe QA (tools/law_build.mjs)`, "",
    `Composition: \`${pascal}\` in \`src/index.law.ts\` (${L.W}x${L.H}, 30 fps, no motion blur). Kit law3d, format ${fmt}. ${C.shots.length} shots, ${dur.toFixed(2)} s.`, "",
    `## Clip QA: ${C.duration} frames x 4 sub-frames, ${hits.size} clip(s)`, "",
    ...(qaLines.length ? qaLines.map((l) => `- ${l}`) : ["- none: no prop or set piece enters a figure's body or head, no two people overlap, nobody sinks below the floor."]), "",
    ...KF.fr.md,
    ...PQ.md,
    `## Frame-0 gate and kit rules`, "", "| check | result | detail |", "|---|---|---|",
    ...gate.map(([k, ok, d, hard]) => `| ${k} | ${ok ? "PASS" : hard ? "**FAIL**" : "warn"} | ${d} |`), "",
    `Frame-0 coverage by subject: ${covs.slice(0, 5).map((c) => `${c.name} ${(c.k * 100).toFixed(0)} %`).join(", ")}.`, "",
  ];
  wf(join(dir, "RECIPE_QA.md"), rep.join("\n"));
  console.log(`clip QA: ${hits.size} clip(s)`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}`);
  return hits.size || hardFail ? 1 : 0;
};


// ------------------------------------------------------------------ LONG-FORM ("format": "landscape")
// glyph cap height (m at scale 1) of each 3D text prop, from its canvas texture (font px / texture px * face size * 0.7),
// and whether the text lies flat (paper, folder: read along the prop's depth) or stands up
const TEXT3D = { sign: [0.1, false], newspaper: [0.046, false], nameplate: [0.032, false], box: [0.035, false], paper: [0.026, true], folder: [0.032, true] };
const longForm = async ({ m, C, recipe, words, dur, slug, pascal, dir, check, qaSample, T0, compileS }) => {
  const L = C.layout, LF = m.LF;
  // ---- clip QA on output frames (every qaSample-th; no sub-frames: long-form renders without motion blur)
  const Tq = Date.now();
  const ov = (p, a) => [0, 1, 2].every((k) => Math.abs(p.c[k] - a.c[k]) < p.h[k] + a.h[k]);
  const hits = new Map();
  const note = (k, t) => { if (!hits.has(k)) hits.set(k, t); };
  for (const t of qaTimes(C.duration, true, qaSample)) {
    const { figs, props } = C.qa(t);
    const sid = C.shotAt(t).id;
    for (const b of figs) {
      if (b.c[1] - b.h[1] < -0.02) note(`${sid} ${b.name} below the floor`, t);
      for (const p of props) if (ov(p, b)) note(`${sid} ${p.name} x ${b.name}`, t);
    }
    const bodies = figs.filter((b) => b.name.endsWith(".body") || b.name.endsWith(".head"));
    for (let i = 0; i < bodies.length; i++) for (let j = i + 1; j < bodies.length; j++) if (bodies[i].name.split(".")[0] !== bodies[j].name.split(".")[0] && ov(bodies[i], bodies[j])) note(`${sid} ${bodies[i].name} x ${bodies[j].name}`, t);
  }
  const qaS = (Date.now() - Tq) / 1000;
  const qaLines = [...hits].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(3)} s (frame ${Math.floor(t * 30)})`);

  // ---- visual-change events besides cuts: camera hits/kicks (slams, gavels, verdicts, shakes, landings, punch-ins),
  //      pose and face changes, prop landings and gavel strikes, device pop-ins (case card, exhibit, verdict, counter,
  //      a counter draining to 0), fx
  const Tg = Date.now();
  const LEAD = 2 / 30;
  const events = [];
  for (const s of C.shots) {
    const ins = (t) => t >= s.a - 1e-6 && t < s.b;
    const push = (t, l) => { if (ins(t)) events.push([t, `${s.id} ${l}`]); };
    for (const [t] of s.kicks) push(t, "hit");
    for (const f of s.figs) { f.segs.slice(1).forEach((g) => push(g.t0 + LEAD, `${f.id} pose ${g.pose}`)); f.faces.forEach((g) => push(g.t0 + LEAD, `${f.id} face ${g.face}`)); }
    for (const p of s.props) { if (p.spec.motion === "popIn" || p.spec.motion === "dropIn" || p.spec.motion === "flyIn") push(p.hit, `${p.key} lands`); for (const h of p.hits) push(h, `${p.key} strike`); }
    for (const d of s.devices) { push(d.t0, d.act.do); if (d.zeroAt !== undefined) push(d.zeroAt, "counter to 0"); }
    for (const f of s.fx) push(f.at, f.fx);
  }
  // ---- captions: share of caption time whose lower-third centre is >= 75 % of the height; shots that moved it
  let capT = 0, capLow = 0;
  const moved = [];
  for (const s of C.shots) {
    if (recipe.captions === "off" || s.spec.caption === "off") continue;
    const a = Math.max(s.a, 1.0), b = s.b; if (b <= a) continue;
    const y = s.capY ?? LF.CAP_Y;
    capT += b - a; if (y >= 0.75 * LF.H) capLow += b - a;
    if (y !== LF.CAP_Y) moved.push(`${s.id}@${s.a.toFixed(1)}s->${(y / 10.8).toFixed(0)}%`);
  }
  const lifted = C.shots.filter((s) => (s.lift ?? 0) > 1e-4).map((s) => `${s.id} +${(s.lift * 100).toFixed(1)} %`);
  // ---- boards: the story devices (DOM) and the 3D text props, sampled every 0.25 s once landed
  const EDGE = 16, bandTop = LF.CAP_Y - LF.CAP_HALF, bandBot = LF.CAP_Y + LF.CAP_HALF;
  const small = new Map(), edge = new Map(), band = new Map();
  const inCol = (x0, x1) => x1 > LF.CAP_SIDE && x0 < L.W - LF.CAP_SIDE;
  const judge = (key, label, x0, x1, y0, y1, px, t) => {
    if (px > 0 && px < 30 && !small.has(key)) small.set(key, `${label} ${px.toFixed(0)} px at ${t.toFixed(1)} s`);
    if ((x0 < EDGE || x1 > L.W - EDGE || y0 < EDGE || y1 > L.H - EDGE) && !edge.has(key)) edge.set(key, `${label} x ${x0.toFixed(0)}-${x1.toFixed(0)} y ${y0.toFixed(0)}-${y1.toFixed(0)} at ${t.toFixed(1)} s`);
    if (y1 > bandTop && y0 < bandBot && inCol(x0, x1) && !band.has(key)) band.set(key, `${label}@${t.toFixed(1)}s`);
  };
  const fsOf = (d) => {
    if (d.kind === "exhibit") return Math.min(L.exhibitFs, L.exhibitLabelFs ?? 34);
    if (d.kind === "verdict") return d.sub ? 64 : L.verdict.fs;
    if (d.kind === "caseCard") return Math.min(52, Math.min(92, (d.w - 120) / Math.max(6, (d.title ?? "").length * 0.62)), d.note ? 36 : 99);
    if (d.kind === "counter") return Math.min(L.board.fsTitle, Math.min(L.board.fsValue, (d.w - 40) / Math.max(3, (d.value ?? "").length * 0.6)));
    return 99;
  };
  const sub3 = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
  const overlaps = new Set();
  const hb = m.hookBox(L, recipe.hook.text);
  for (let t = 0; t < dur; t += 0.25) {
    const s = C.shotAt(t), cam = C.camAt(t);
    // cards overlapping each other or the hook (the case-file card's tab reaches 46 px above it)
    const boxes = C.devicesAt(t).filter((d) => d.u >= 0.3).map((d) => ({ k: d.kind, x: d.x, y: d.kind === "caseCard" ? d.y - 23 : d.y, w: d.w, h: d.kind === "caseCard" ? d.h + 46 : d.h }));
    if (t <= C.hookUntil || (C.hookAgain !== null && t >= C.hookAgain)) boxes.push({ k: "hook", ...hb });
    const hitR = (a, b) => Math.abs(a.x - b.x) * 2 < a.w + b.w && Math.abs(a.y - b.y) * 2 < a.h + b.h;
    for (let i = 0; i < boxes.length; i++) for (let j = i + 1; j < boxes.length; j++) if (hitR(boxes[i], boxes[j])) overlaps.add(`${s.id} ${boxes[i].k}/${boxes[j].k}`);
    for (const d of C.devicesAt(t)) {
      if (d.u < 0.99) continue;
      const label = `${s.id} ${d.kind} "${d.text ?? d.title ?? d.value ?? ""}"`;
      judge(`${s.id}.${d.key}`, label, d.x - d.w / 2, d.x + d.w / 2, d.y - d.h / 2, d.y + d.h / 2, 0.7 * fsOf(d), t);
    }
    for (const p of s.props) {
      const spec = TEXT3D[p.spec.kit];
      if (!spec || !p.text || t < p.a || t >= p.b || p.show(t) < 0.5 || t < (p.spec.motion ? p.hit : p.a) + 0.3) continue;
      const pl = p.place(t), bx = m.KIT_BOX[p.spec.kit];
      const cy = Math.cos(pl.yaw), sy = Math.sin(pl.yaw);
      const corner = (dx, dy, dz) => { const lx = bx.c[0] + dx * bx.h[0], ly = bx.c[1] + dy * bx.h[1], lz = bx.c[2] + dz * bx.h[2]; return [pl.p[0] + (lx * cy + lz * sy) * pl.s, pl.p[1] + ly * pl.s, pl.p[2] + (-lx * sy + lz * cy) * pl.s]; };
      const qs = [];
      for (const dx of [-1, 1]) for (const dy of [-1, 1]) for (const dz of [-1, 1]) { const q = m.project(cam, corner(dx, dy, dz), L); if (q) qs.push(q); }
      if (qs.length < 8) continue;
      const x0 = Math.min(...qs.map((q) => q.x)), x1 = Math.max(...qs.map((q) => q.x)), y0 = Math.min(...qs.map((q) => q.y)), y1 = Math.max(...qs.map((q) => q.y));
      if (x1 < 0 || x0 > L.W || y1 < 0 || y0 > L.H) continue;
      // glyph height on screen: a glyph-tall segment along the text's up axis (world up, or the prop's depth when flat)
      const g = spec[0] * pl.s, c0 = corner(0, 0, 0);
      const ax = spec[1] ? [sy * g / 2, 0, cy * g / 2] : [0, g / 2, 0];
      const qa = m.project(cam, [c0[0] + ax[0], c0[1] + ax[1], c0[2] + ax[2]], L), qb = m.project(cam, sub3(c0, ax), L);
      const px = qa && qb ? Math.hypot(qa.x - qb.x, qa.y - qb.y) : 0;
      judge(`${s.id}.${p.key}`, `${s.id} ${p.key} "${String(p.text).replace(/\n/g, " ")}"`, x0, x1, y0, y1, px, t);
    }
  }
  const { gate, pacing } = kitLongGate({
    shots: C.shots.map((s) => ({ id: s.id, a: s.a, b: s.b, set: s.set, beat: !!s.spec.beat })),
    events, chapters: C.chapters, words, dur, audio: C.audio, hookUntil: C.hookUntil, hookText: recipe.hook.text.replace(/\*/g, ""),
    caps: { share: capT ? capLow / capT : 1, moved }, boards: { small: [...small.values()], edge: [...edge.values()], band: [...band.values()] },
  });
  const gateS = (Date.now() - Tg) / 1000;
  const KFL = runFraming("law3d", C, m, recipe, true, qaSample);
  gate.push(...KFL.rows);
  const PQ = polishQA({ kit: "law3d", C, m, recipe, words, landscape: true, step: qaSample });
  gate.push(...PQ.rows);
  const chTxt = chaptersTxt(C.chapters);
  const hardFail = gate.some((g) => g[3] && !g[1]);
  const rep = kitLongReport({ framingMd: [...KFL.fr.md, ...PQ.md], slug, kit: "law3d", tool: "law_build.mjs", entry: "src/index.law.ts", pascal, C, dur, words, chapters: C.chapters, hits, qaLines, qaSample, qaS, gate, gateS, pacing, chTxt,
    extra: [`Cards overlapping each other or the hook: ${overlaps.size ? [...overlaps].join(", ") : "none"}.`, "", `Caption-safe framing (lower third): ${lifted.length ? `lifted ${lifted.join(", ")}` : "no shot needed a lift"}; caption moved in ${moved.length ? moved.join(", ") : "no shot"}.`, ""] });
  if (!check) {
    writeFileSync(join(dir, "RECIPE_QA.md"), rep.join("\n"));
    writeFileSync(join(dir, "chapters.txt"), chTxt);
  }
  console.log(`clip QA: ${hits.size} clip(s) over ${Math.ceil(C.duration / qaSample)} sampled frames (every ${qaSample}) in ${qaS.toFixed(2)} s`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  if (overlaps.size) console.log(`warn  cards overlap: ${[...overlaps].join(", ")}`);
  console.log(`chapters:\n${chTxt.trimEnd()}`);
  console.log(`timings: compile ${compileS.toFixed(2)} s, clip QA ${qaS.toFixed(2)} s, gate ${gateS.toFixed(2)} s, total ${((Date.now() - T0) / 1000).toFixed(2)} s`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}, ${join(dir, "chapters.txt")}`);
  return hits.size || hardFail ? 1 : 0;
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(await main(process.argv.slice(2)));
