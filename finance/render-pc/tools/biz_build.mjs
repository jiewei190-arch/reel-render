// biz_build.mjs: a biz3d recipe ("kit": "biz3d") -> a Remotion composition, then the clip QA and the frame-0 gate.
//   node tools/biz_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>] [--qa-sample N]
//   (node tools/recipe_build.mjs <slug> forwards here when recipe.json says "kit": "biz3d")
// Reads   <shorts>/<slug>/recipe.json + vo/timings.json (finance/longform/<slug> when only that exists: tools/kit_long.mjs)
// Writes  src/biz/gen/<slug_>.biz.gen.ts      the recipe + word timings as a TS module
//         src/biz/registry.gen.ts             every *.biz.gen.ts (BizRoot registers <Pascal>Recipe)
//         out/tmp/<slug>.cues.json            the audio plan (STORY_CUES=<file> python tools/story_mix.py ...)
//         <shorts>/<slug>/RECIPE_QA.md        the QA + gate report
//         <dir>/chapters.txt                  long-form only: the YouTube chapter lines
// "format": "landscape" (1920x1080 long-form, LONGFORM.md): clip QA every Nth output frame (--qa-sample N) and the shared
// long-form gate (tools/kit_long.mjs: chapters, pacing, lower-third captions, readable boards) instead of the Shorts
// frame-0 gate. Shorts always get the full every-frame x 4 QA and the kit gate below, unchanged.
// Nothing here touches the Block Money or tech3d registries.
import { build } from "esbuild";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { chaptersTxt, kitArgs, kitLongGate, kitLongReport, qaTimes } from "./kit_long.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const main = async (argv) => {
  const T0 = Date.now();
  const A = kitArgs(argv);
  if (A.err) { console.error(A.err === "usage" ? "usage: node tools/biz_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>] [--qa-sample N]" : A.err); return 2; }
  const { slug, SHORTS, dir, noQa, check, qaSample, qaSampleGiven } = A;
  const folder = SHORTS === resolve(ROOT, "../longform") ? "longform" : "shorts";
  const recipe = JSON.parse(readFileSync(join(dir, "recipe.json"), "utf8"));
  const timings = JSON.parse(readFileSync(join(dir, "vo/timings.json"), "utf8"));
  if (recipe.slug !== slug) { console.error(`recipe.slug "${recipe.slug}" != folder "${slug}"`); return 2; }
  if (recipe.kit !== "biz3d") { console.error(`recipe.kit is "${recipe.kit}", not "biz3d": use tools/recipe_build.mjs`); return 2; }

  // ---------------------------------------------------------------- 1) compile in node (before any file is written)
  const stub = { name: "stub", setup(b) {
    b.onResolve({ filter: /^(remotion|@remotion\/.*|@react-three\/.*)$/ }, (a) => ({ path: a.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "const P=new Proxy(function(){return P},{get:(t,k)=>k==='__esModule'?false:P,apply:()=>P,construct:()=>P}); module.exports=P;", loader: "js" }));
  } };
  const r = await build({ entryPoints: [join(ROOT, "tools/biz_entry.ts")], bundle: true, write: false, format: "esm", platform: "node", plugins: [stub], jsx: "automatic", logLevel: "error" });
  mkdirSync(join(ROOT, "out/tmp"), { recursive: true });
  const bundleF = join(ROOT, "out/tmp/biz_build.bundle.mjs");
  writeFileSync(bundleF, r.outputFiles[0].text);
  const m = await import(pathToFileURL(bundleF).href + "?" + Date.now());
  const words = timings.turns.flatMap((tn) => tn.words.map((w) => ({ w: w.w, turn: tn.turn, t: w.t, end: w.end })));
  const vo = timings.source?.duration;
  let C;
  try { C = m.compileBiz(recipe, words, vo); } catch (e) { console.error(`COMPILE ERROR: ${e.message}`); return 1; }
  const L = C.layout;

  // ---------------------------------------------------------------- 2) codegen
  const wf = (f, txt) => { if (!check) writeFileSync(f, txt); };
  const us = slug.replace(/-/g, "_");
  const pascal = slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("") + "Recipe";
  mkdirSync(join(ROOT, "src/biz/gen"), { recursive: true });
  wf(join(ROOT, `src/biz/gen/${us}.biz.gen.ts`),
    `// generated by tools/biz_build.mjs from finance/${folder}/${slug}/recipe.json + vo/timings.json; do not edit\n` +
    `import type { Word } from "../../fin/recipe/types";\nimport type { BizRecipe } from "../types";\n\n` +
    `export const ID = ${JSON.stringify(pascal)};\nexport const VO_DURATION: number | undefined = ${vo === undefined ? "undefined" : vo};\n` +
    `export const RECIPE: BizRecipe = ${JSON.stringify(recipe, null, 1)};\n` +
    `export const WORDS: Word[] = ${JSON.stringify(words)};\n`);
  const gens = check ? [] : readdirSync(join(ROOT, "src/biz/gen")).filter((f) => f.endsWith(".biz.gen.ts")).sort();
  wf(join(ROOT, "src/biz/registry.gen.ts"),
    `// generated by tools/biz_build.mjs; do not edit (lists src/biz/gen/*.biz.gen.ts)\nimport type { Word } from "../fin/recipe/types";\nimport type { BizRecipe } from "./types";\n` +
    gens.map((f, i) => `import * as B${i} from "./gen/${f.replace(/\.ts$/, "")}";`).join("\n") +
    `\n\nexport const BIZ_RECIPES: { id: string; recipe: BizRecipe; words: Word[]; vo?: number }[] = [\n` +
    gens.map((_, i) => `  { id: B${i}.ID, recipe: B${i}.RECIPE, words: B${i}.WORDS, vo: B${i}.VO_DURATION },`).join("\n") + `\n];\n`);
  if (!check) console.log(`wrote src/biz/gen/${us}.biz.gen.ts and the biz registry (${gens.length} recipe(s)); composition ${pascal} in src/index.biz.ts (${L.id} ${L.W}x${L.H})`);
  const dur = C.duration / 30;
  if (!check) writeFileSync(join(ROOT, `out/tmp/${slug}.cues.json`), JSON.stringify({ [pascal]: { music: C.audio.music, musicDb: -12, cues: C.audio.cues, duration: dur, cuts: C.shots.map((s) => s.a) } }));
  console.log(`compiled ${C.shots.length} shots, ${dur.toFixed(2)} s (${C.duration} frames), ${C.audio.cues.length} sfx cues`);
  if (noQa) return 0;
  if (C.landscape) return longGate({ m, C, L, recipe, words, slug, dir, pascal, dur, check, qaSample, T0 });
  if (qaSampleGiven) console.log(`note: --qa-sample is for long-form; a Short gets the full QA (every frame x 4 sub-frames)`);

  // ---------------------------------------------------------------- 3) clip QA (every frame x 4 sub-frames)
  const ov = (p, a) => [0, 1, 2].every((k) => Math.abs(p.c[k] - a.c[k]) < p.h[k] + a.h[k]);
  const hits = new Map();
  const note = (k, t) => { if (!hits.has(k)) hits.set(k, t); };
  for (let f = 0; f < C.duration * 4; f++) {
    const t = f / 120;
    const { execs, props } = C.qa(t);
    const sid = C.shotAt(t).id;
    for (const e of execs) for (const p of props) if (ov(p, e)) note(`${sid} ${p.name} x ${e.name}`, t);
    for (const st of C.execsAt(t)) if (st.y < -0.01) note(`${sid} ${st.id} below the floor`, t);
    const bodies = execs.filter((b) => b.name.endsWith(".body"));
    for (let i = 0; i < bodies.length; i++) for (let j = i + 1; j < bodies.length; j++) if (ov(bodies[i], bodies[j])) note(`${sid} ${bodies[i].name} x ${bodies[j].name}`, t);
  }
  const qaLines = [...hits].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(3)} s (frame ${Math.floor(t * 30)})`);

  // ---------------------------------------------------------------- 4) gate
  const sub3 = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
  const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
  const crs = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
  const nrm = (a) => { const l = Math.hypot(...a) || 1; return a.map((x) => x / l); };
  const coverage = (cam, b) => {
    const f = nrm(sub3(cam.look, cam.pos)), rgt = nrm(crs(f, [0, 1, 0])), up = crs(rgt, f), th = Math.tan((cam.fov * Math.PI) / 360), asp = L.W / L.H;
    let y0 = Infinity, y1 = -Infinity, x0 = Infinity, x1 = -Infinity;
    for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) {
      const p = [b.c[0] + sx * b.h[0], b.c[1] + sy * b.h[1], b.c[2] + sz * b.h[2]];
      const d = sub3(p, cam.pos), z = dot(d, f);
      if (z <= 0.05) return 0;
      const ny = dot(d, up) / (z * th), nx = dot(d, rgt) / (z * th * asp);
      y0 = Math.min(y0, ny); y1 = Math.max(y1, ny); x0 = Math.min(x0, nx); x1 = Math.max(x1, nx);
    }
    if (x1 < -1 || x0 > 1) return 0;
    return Math.max(0, Math.min(1, y1) - Math.max(-1, y0)) / 2;
  };
  const cam0 = C.camAt(0);
  const subjects = [];
  for (const st of C.execsAt(0)) { const h = st.seated ? 0.62 : 0.9; subjects.push({ name: st.id, exec: true, c: [st.x, st.y + (st.seated ? 0.95 : 0.9) * st.s, st.z], h: [0.3 * st.s, h * st.s, 0.2 * st.s] }); }
  for (const b of C.qa(0).props) if (!b.name.startsWith("store") && b.name !== "table" && b.name !== "windowWall") subjects.push({ name: b.name, c: b.c, h: b.h });
  const covs = subjects.map((b) => ({ name: b.name, exec: !!b.exec, k: coverage(cam0, b) })).sort((a, b) => b.k - a.k);
  const best = covs[0] ?? { name: "nothing", k: 0 };
  const hookText = recipe.hook.text;
  const hookWords = hookText.replace(/\*/g, "").trim().split(/\s+/).length;
  const hookLines = m.hookLines(hookText);
  const accent = hookText.match(/\*[^*]+\*/g) ?? [];
  const hookW = m.hookWidth(L, hookText);
  const stakeRe = /\$|\d/;
  let stakeAt = null;
  for (let f = 0; f <= 15 && stakeAt === null; f++) if (C.textsAt(f / 30).some((s) => stakeRe.test(s))) stakeAt = f / 30;
  const pose0 = new Map(C.execsAt(0).map((b) => [b.id, b.pose]));
  let poseAt = null;
  for (let f = 1; f <= 45 && poseAt === null; f++) for (const b of C.execsAt(f / 30)) if (!pose0.has(b.id) || pose0.get(b.id) !== b.pose) { poseAt = f / 30; break; }
  const PUNCH = /^(impact|drop|crash|boom|thud|punch|stamp|coins|scratch|paper|rip|cash)/;
  const sfx0 = C.audio.cues.filter((c) => c.t <= 0.02);
  const moves = new Set();
  for (const s of C.shots) { if (s.a > 0 && s.a <= 3.0) moves.add(`cut ${s.a.toFixed(2)}`); for (const [t] of s.kicks) if (t <= 3.0 && t > 0.05) moves.add(`hit ${t.toFixed(2)}`); }
  const early = C.shots.filter((s) => s.a < 1.0);
  const band = [L.cap.centre - L.cap.band, L.cap.centre + L.cap.band];
  let capT = 0, capOk = 0;
  const capBad = new Set(), textHead = new Set(), textBand = new Set(), textText = new Set(), staticF = [], hookHead = new Set();
  const headRect = (cam, st) => { const f = m.execHead(st); const q = C.project(cam, f.c); if (!q || q.x < -100 || q.x > L.W + 100) return null; const r = f.r * q.k; return { x: q.x, y: q.y, w: 2 * r, h: 2 * r }; };
  const hitR = (a, b) => Math.abs(a.x - b.x) * 2 < a.w + b.w && Math.abs(a.y - b.y) * 2 < a.h + b.h;
  const hookN = hookLines.length, hookBox = { x: L.W / 2, y: L.hook.top + (hookN * L.hook.fs * 1.04 + 48) / 2, w: hookW + 80, h: hookN * L.hook.fs * 1.04 + 48 };
  let prevCam = null;
  for (let f = 0; f < C.duration; f++) {
    const t = f / 30, s = C.shotAt(t), cam = C.camAt(t);
    if (prevCam && C.shotAt((f - 1) / 30) === s) {
      const d = Math.hypot(...sub3(cam.pos, prevCam.pos)) + Math.hypot(...sub3(cam.look, prevCam.look)) + Math.abs(cam.fov - prevCam.fov) * 0.01 + Math.abs((cam.roll ?? 0) - (prevCam.roll ?? 0)) * 0.01;
      if (d < 2e-4) staticF.push(f);
    }
    prevCam = cam;
    const heads = C.execsAt(t).map((st) => headRect(cam, st)).filter(Boolean);
    const capOn = t >= L.cap.from && recipe.captions !== "off" && s.spec.caption !== "off";
    if (capOn) { capT++; if (heads.every((r) => r.y + r.h / 2 < band[0] || r.y - r.h / 2 > band[1])) capOk++; else capBad.add(s.id); }
    const boxes = [...C.labelsAt(t).filter((l) => l.u >= 0.3).map((l) => ({ ...l, name: `label ${l.text}` })), ...C.devicesAt(t).filter((d) => d.u >= 0.3 && d.kind !== "decision").map((d) => ({ ...d, name: d.kind }))];
    for (const b of boxes) {
      if (heads.some((r) => hitR(b, r))) textHead.add(`${b.name}@${t.toFixed(1)}s`);
      if (b.y + b.h / 2 > band[0] - 1) textBand.add(`${b.name}@${t.toFixed(1)}s`);
    }
    for (let i = 0; i < boxes.length; i++) for (let j = i + 1; j < boxes.length; j++) if (hitR(boxes[i], boxes[j])) textText.add(`${boxes[i].name}/${boxes[j].name}@${t.toFixed(1)}s`);
    if (t <= C.hookUntil || (C.hookAgain !== null && t >= C.hookAgain)) {
      for (const r of heads) if (hitR(hookBox, r)) hookHead.add(`${s.id}@${t.toFixed(1)}s`);
      for (const b of boxes) if (hitR(hookBox, b)) textText.add(`hook/${b.name}@${t.toFixed(1)}s`);
    }
  }
  const capShare = capT ? capOk / capT : 1;
  const oneAtATime = [];
  for (const s of C.shots) { const ts = s.labels.map((l) => l.t0).sort((a, b) => a - b); for (let i = 1; i < ts.length; i++) if (ts[i] - ts[i - 1] < 0.3) oneAtATime.push(`${s.id} ${ts[i - 1].toFixed(2)}/${ts[i].toFixed(2)} s`); }
  const nLabels = C.shots.reduce((n, s) => n + s.labels.length, 0);
  const firstCut = C.shots.length > 1 ? C.shots[1].a : dur;
  const lastShot = C.shots[C.shots.length - 1], firstShot = C.shots[0];
  const loopy = C.hookAgain !== null && JSON.stringify(lastShot.spec.cam.target) === JSON.stringify(firstShot.spec.cam.target);
  const fmt = recipe.format ?? "short";
  const long = fmt === "long" || fmt === "landscape";
  const lenOk = long ? dur >= 300 && dur <= 480 : dur >= 30 && dur <= 55;
  const flys = C.shots.filter((s) => s.spec.cam.preset === "chartFly");
  const devKinds = new Set(C.shots.flatMap((s) => s.devices.map((d) => d.spec.do)));
  const hasExec0 = C.execsAt(0).length > 0;
  const gate = [
    ["frame 0 is close: a subject covers >= 50 % of the frame height", best.k >= 0.5, `${best.name} ${(best.k * 100).toFixed(0)} %`, true],
    ["hook at frame 0: <= 5 words, <= 2 lines that fit, exactly one *accent* word", C.hookUntil > 0 && hookWords <= 5 && hookLines.length <= 2 && hookW <= L.hook.maxW && accent.length === 1, `"${hookText}" (${hookWords} words, ${hookLines.length} line(s), widest ~${hookW.toFixed(0)} px of ${L.hook.maxW}, accent: ${accent.join(" ") || "none"}, until ${C.hookUntil.toFixed(2)} s)`, true],
    ["the dollar stake / a number on screen by 0.5 s", stakeAt !== null, stakeAt === null ? "none by 0.5 s" : `at ${stakeAt.toFixed(2)} s`, true],
    ["first spoken word by 0.2 s", words[0].t <= 0.2, `${words[0].w} at ${words[0].t.toFixed(2)} s`, true],
    ["a sound punch at 0.00 s", sfx0.some((c) => PUNCH.test(c.sfx)), sfx0.map((c) => c.sfx).join(", ") || "none", true],
    ["2-3 cuts or big moves in the first 3 s", moves.size >= 2, [...moves].join(", ") || "none", true],
    ["music + an SFX at frame 0", !!C.audio.music && C.audio.cues.some((c) => c.t <= 0.05), `${C.audio.music}, ${sfx0.map((c) => c.sfx).join(", ")}`, true],
    ["an acting beat by 1.5 s (a frame-0 executive changes pose)", !hasExec0 || poseAt !== null, !hasExec0 ? "no executive at frame 0" : poseAt === null ? "no pose change by 1.5 s" : `at ${poseAt.toFixed(2)} s`, true],
    ["no wide shot in the first 1 s", early.every((s) => s.spec.cam.preset !== "wide"), early.map((s) => `${s.id} ${s.spec.cam.preset}`).join(", "), true],
    ["frame-0 shot cuts away by ~1.0 s (first cut <= 1.25 s)", firstCut <= 1.25, `first cut at ${firstCut.toFixed(2)} s`, true],
    ["heads clear of the caption band on >= 90 % of caption time", capShare >= 0.9, `${(capShare * 100).toFixed(0)} %${capBad.size ? `; a head in the band in ${[...capBad].join(", ")}` : ""}`, true],
    ["labels: <= 3 words (compile-enforced), one at a time (>= 0.3 s apart)", oneAtATime.length === 0, `${nLabels} label(s)${oneAtATime.length ? `; too close: ${oneAtATime.join(", ")}` : ""}`, true],
    ["no label or device card over a head", textHead.size === 0, [...textHead].slice(0, 6).join(", ") || "none", true],
    ["the hook card never covers a head", hookHead.size === 0, [...hookHead].slice(0, 6).join(", ") || "clear", true],
    ["text cards never overlap each other or the hook", textText.size === 0, [...textText].slice(0, 6).join(", ") || "none", true],
    ["label and device cards above the caption band", textBand.size === 0, [...textBand].slice(0, 6).join(", ") || "all above", true],
    ["no static frames: the camera moves on every frame (freeze-frames included)", staticF.length === 0, staticF.length ? `${staticF.length} still frame(s), first ${staticF.slice(0, 5).join(", ")}` : "moves on every frame", true],
    ["the signature chart flythrough is used", flys.length > 0, flys.length ? flys.map((s) => `${s.id} ${s.a.toFixed(2)}-${s.b.toFixed(2)} s`).join(", ") : "no chartFly shot", false],
    ["story devices: a company card and THE DECISION", devKinds.has("company") && devKinds.has("decision"), [...devKinds].join(", ") || "none", false],
    ["loop ending: the hook comes back and the last shot frames the first shot's subject", loopy, `hook again ${C.hookAgain === null ? "not set" : `at ${C.hookAgain.toFixed(2)} s`}; last target ${JSON.stringify(lastShot.spec.cam.target)}`, false],
    [long ? "length 5-8 min" : "length 30-55 s", lenOk, `${dur.toFixed(2)} s`, false],
  ];
  const hardFail = gate.some((g) => g[3] && !g[1]);
  const rep = [
    `# ${slug}: biz3d recipe QA (tools/biz_build.mjs)`, "",
    `Composition: \`${pascal}\` in \`src/index.biz.ts\` (${L.id} ${L.W}x${L.H}, 30 fps, no motion blur). ${C.shots.length} shots, ${dur.toFixed(2)} s.`, "",
    `## Clip QA: ${C.duration} frames x 4 sub-frames, ${hits.size} clip(s)`, "",
    ...(qaLines.length ? qaLines.map((l) => `- ${l}`) : ["- none: no executive's body or head enters a set blocker, a kit prop or another executive; nobody below the floor."]), "",
    `## Frame-0 gate and kit rules`, "", "| check | result | detail |", "|---|---|---|",
    ...gate.map(([k, ok, d, hard]) => `| ${k} | ${ok ? "PASS" : hard ? "**FAIL**" : "warn"} | ${d} |`), "",
    `Frame-0 coverage by subject: ${covs.slice(0, 5).map((c) => `${c.name} ${(c.k * 100).toFixed(0)} %`).join(", ")}.`, "",
  ];
  wf(join(dir, "RECIPE_QA.md"), rep.join("\n"));
  console.log(`clip QA: ${hits.size} clip(s)`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}`);
  return hits.size || hardFail ? 1 : 0;
};

// ---------------------------------------------------------------- LONG-FORM ("format": "landscape")
const clipQA = (C, times) => {
  const ov = (p, a) => [0, 1, 2].every((k) => Math.abs(p.c[k] - a.c[k]) < p.h[k] + a.h[k]);
  const hits = new Map();
  const note = (k, t) => { if (!hits.has(k)) hits.set(k, t); };
  for (const t of times) {
    const { execs, props } = C.qa(t);
    const sid = C.shotAt(t).id;
    for (const e of execs) for (const p of props) if (ov(p, e)) note(`${sid} ${p.name} x ${e.name}`, t);
    for (const st of C.execsAt(t)) if (st.y < -0.01) note(`${sid} ${st.id} below the floor`, t);
    const bodies = execs.filter((b) => b.name.endsWith(".body"));
    for (let i = 0; i < bodies.length; i++) for (let j = i + 1; j < bodies.length; j++) if (ov(bodies[i], bodies[j])) note(`${sid} ${bodies[i].name} x ${bodies[j].name}`, t);
  }
  return hits;
};
/** the smallest font (px at 1080p) each card kind draws (hud.tsx), for the readability check */
const minFont = (L, kind, spec) => {
  switch (kind) {
    case "label": return L.label.fs;
    case "tag": return L.tag.fs;
    case "company": return spec.tagline ? L.company.yearFs * 0.8 : spec.year !== undefined ? L.company.yearFs : L.company.nameFs;
    case "decision": return spec.sub ? L.decision.subFs : L.decision.fs;
    case "counter": return L.counter.titleFs;
    case "worth": return L.worth.labelFs;
    case "board": return L.board.titleFs;
    case "stamp": return L.decision.fs * 0.85;
    default: return 99;
  }
};
const longGate = ({ m, C, L, recipe, words, slug, dir, pascal, dur, check, qaSample, T0 }) => {
  const tq = Date.now();
  const hits = clipQA(C, qaTimes(C.duration, true, qaSample));
  const qaS = (Date.now() - tq) / 1000;
  const qaLines = [...hits].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(3)} s (frame ${Math.floor(t * 30)})`);
  const tg = Date.now();
  // visual-change events besides cuts: camera hits/kicks, prop motions, pose changes, label/device pop-ins, actions, fx
  const events = [];
  for (const s of C.shots) {
    for (const [t] of s.kicks) events.push([t, `hit ${s.id}`]);
    for (const p of s.props) if (p.spec.motion === "dropIn" || p.spec.motion === "popIn") events.push([p.hit, `${p.spec.motion} ${p.key}`]);
    for (const e of s.execs) for (const g of e.segs.slice(1)) if (g.t0 > s.a && g.t0 < s.b) events.push([g.t0, `pose ${e.id} ${g.pose}`]);
    for (const l of s.labels) events.push([l.t0, `label ${l.text}`]);
    for (const d of s.devices) events.push([d.t0, `${d.spec.do}`]);
    for (const f of s.fx) events.push([f.at, `fx ${f.fx}`]);
    for (const ac of s.spec.actions ?? []) { const t = C.at(ac.at); events.push([t, `${ac.do}`]); if (ac.do === "crack" && ac.collapse !== undefined) events.push([C.at(ac.collapse), "collapse"]); }
  }
  // lower-third captions: the share of caption time with the centre in the lower quarter; and the shots that moved it
  let capT = 0, capOk = 0;
  const moved = new Set();
  const textBox = { small: new Map(), edge: new Map(), band: new Map() };
  const EX = 0.015 * L.W, EY = 0.015 * L.H, bandTop = L.cap.centre - L.cap.band;
  for (let f = 0; f < C.duration; f += qaSample) {
    const t = f / 30, s = C.shotAt(t);
    const capOn = t >= L.cap.from && recipe.captions !== "off" && s.spec.caption !== "off" && (s.spec.caption && s.spec.caption !== "auto" || words.some((w) => t >= w.t - 0.05 && t < w.end + 0.6));
    const y = C.capY(s);
    if (capOn) { capT++; if (y >= 0.75 * L.H) capOk++; }
    if (y !== L.cap.centre) moved.add(`${s.id} ${y.toFixed(0)}`);
    const boxes = [
      ...C.labelsAt(t).filter((l) => l.u >= 0.9).map((l) => ({ ...l, kind: "label", name: `label "${l.text}"`, spec: {} })),
      ...C.tagsAt(t).filter((g) => g.u >= 0.9).map((g) => ({ ...g, kind: "tag", name: `tag ${g.text}`, spec: {} })),
      ...C.devicesAt(t).filter((d) => d.u >= 0.9).map((d) => ({ ...d, name: d.kind })),
    ];
    for (const b of boxes) {
      const key = `${s.id} ${b.name}`;
      const px = minFont(L, b.kind, b.spec);
      if (px < 30 && !textBox.small.has(key)) textBox.small.set(key, `${key} ${px.toFixed(0)} px`);
      const x0 = b.x - b.w / 2, x1 = b.x + b.w / 2, y0 = b.y - b.h / 2, y1 = b.y + b.h / 2;
      if ((x0 < EX || x1 > L.W - EX || y0 < EY || y1 > L.H - EY) && b.kind !== "decision" && !textBox.edge.has(key)) textBox.edge.set(key, `${key} [${x0.toFixed(0)},${y0.toFixed(0)} - ${x1.toFixed(0)},${y1.toFixed(0)}] at ${t.toFixed(1)} s`);
      if (y1 > bandTop && b.kind !== "decision" && !textBox.band.has(key)) textBox.band.set(key, `${key} @${t.toFixed(1)}s`);
    }
  }
  const caps = { share: capT ? capOk / capT : 1, moved: [...moved] };
  const shots = C.shots.map((s) => ({ id: s.id, a: s.a, b: s.b, set: s.set, beat: !!s.spec.beat }));
  const hookText = recipe.hook.text.replace(/\*/g, "");
  const { gate, pacing } = kitLongGate({ shots, events, chapters: C.chapters, words, dur, audio: C.audio, hookUntil: C.hookUntil, hookText, caps, boards: { small: [...textBox.small.values()], edge: [...textBox.edge.values()], band: [...textBox.band.values()] } });
  const gateS = (Date.now() - tg) / 1000;
  const chTxt = chaptersTxt(C.chapters);
  const extra = [
    `## biz3d landscape notes`, "",
    `- Lens: the shared 16:9 rule (landscapeLens per preset; vertical fov kept). Caption-safe framing lifted ${C.lifted.length} shot(s)${C.lifted.length ? `: ${C.lifted.map((x) => `${x.id} face ${x.from.toFixed(3)} -> ${x.to.toFixed(3)}`).join(", ")}` : ""}.`,
    `- Lower-third caption centre moved on: ${caps.moved.join(", ") || "none"} (default ${L.cap.centre} px).`, "",
  ];
  const rep = kitLongReport({ slug, kit: "biz3d", tool: "biz_build.mjs", entry: "src/index.biz.ts", pascal, C, dur, words, chapters: C.chapters, hits, qaLines, qaSample, qaS, gate, gateS, pacing, chTxt, extra });
  if (!check) { writeFileSync(join(dir, "RECIPE_QA.md"), rep.join("\n")); writeFileSync(join(dir, "chapters.txt"), chTxt); }
  console.log(`clip QA: ${hits.size} clip(s) over ${Math.ceil(C.duration / qaSample)} frames (every ${qaSample === 1 ? "frame" : `${qaSample}th frame`}), ${qaS.toFixed(2)} s`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  if (C.lifted.length) console.log(`caption-safe framing: lifted ${C.lifted.map((x) => `${x.id} ${x.from.toFixed(3)}->${x.to.toFixed(3)}`).join(", ")}`);
  console.log(`timings: clip QA ${qaS.toFixed(2)} s, long-form gate ${gateS.toFixed(2)} s, total ${((Date.now() - T0) / 1000).toFixed(2)} s`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}; chapters: ${join(dir, "chapters.txt")}`);
  const hardFail = gate.some((g) => g[3] && !g[1]);
  return hits.size || hardFail ? 1 : 0;
};

