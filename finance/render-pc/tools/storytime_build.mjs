// storytime_build.mjs: a storytime recipe ("kit": "storytime", KIT_STORYTIME.md) -> a Remotion composition + its QA.
//   node tools/storytime_build.mjs <slug> [--check] [--no-qa] [--shorts <dir>]
//   (node tools/recipe_build.mjs <slug> forwards here when recipe.json says "kit": "storytime")
// Reads   <shorts>/<slug>/recipe.json, vo/timings.json (turns = script lines, each with its speaker), vo/amp.json
//         (python3 tools/storytime_amp.py vo/voice.mp3 vo/amp.json: loudness per frame for the mouth flaps)
// Writes  src/storytime/gen/<slug_>.story.gen.ts, src/storytime/registry.gen.ts, <shorts>/<slug>/RECIPE_QA.md
// QA: 3D clips (the two leads' heads/bodies, leads vs set blockers), framing R1-R6 (tools/framing_qa.mjs, every output
// frame), text-fit of every caption chunk, and the storytime rules (cut rhythm, close-ups, captions, mouths, the end).
// Exit 1 on a clip or a hard FAIL. --check writes nothing.
import { build } from "esbuild";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { kitFraming } from "./framing_qa.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const main = async (argv) => {
  const T0 = Date.now();
  const si = argv.indexOf("--shorts");
  const slug = argv.find((a, i) => !a.startsWith("--") && argv[i - 1] !== "--shorts" && argv[i - 1] !== "--qa-sample");
  if (!slug || !/^[a-z0-9-]+$/.test(slug)) { console.error("usage: node tools/storytime_build.mjs <slug> [--check] [--no-qa] [--shorts <dir>]"); return 2; }
  const SHORTS = si >= 0 ? resolve(argv[si + 1]) : resolve(ROOT, "../shorts");
  const check = argv.includes("--check"), noQa = argv.includes("--no-qa");
  const dir = join(SHORTS, slug);
  const recipe = JSON.parse(readFileSync(join(dir, "recipe.json"), "utf8"));
  const timings = JSON.parse(readFileSync(join(dir, "vo/timings.json"), "utf8"));
  const ampF = join(dir, "vo/amp.json");
  const amp = existsSync(ampF) ? JSON.parse(readFileSync(ampF, "utf8")).amp : [];
  if (!amp.length) console.log("warn  no vo/amp.json: mouths will not move (python3 tools/storytime_amp.py vo/voice.mp3 vo/amp.json)");
  if (recipe.slug !== slug) { console.error(`recipe.slug "${recipe.slug}" != folder "${slug}"`); return 2; }
  if (recipe.kit !== "storytime") { console.error(`recipe.kit is "${recipe.kit}", not "storytime"`); return 2; }
  const words = timings.turns.flatMap((tn) => tn.words.map((w) => ({ w: w.w, turn: tn.turn, t: w.t, end: w.end })));
  const vo = timings.source?.duration;
  const us = slug.replace(/-/g, "_");
  const pascal = slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("") + "Recipe";
  const wf = (f, txt) => { if (!check) writeFileSync(f, txt); };
  // timing speakers must match the recipe's lines
  for (const tn of timings.turns) if (tn.speaker && recipe.lines[String(tn.turn)] && recipe.lines[String(tn.turn)].speaker !== tn.speaker) { console.error(`line ${tn.turn}: timings say speaker "${tn.speaker}", recipe.lines says "${recipe.lines[String(tn.turn)].speaker}"`); return 1; }

  // ---------------------------------------------------------------- 1) codegen
  mkdirSync(join(ROOT, "src/storytime/gen"), { recursive: true });
  wf(join(ROOT, `src/storytime/gen/${us}.story.gen.ts`),
    `// generated by tools/storytime_build.mjs from finance/shorts/${slug}/recipe.json + vo/timings.json + vo/amp.json; do not edit\n` +
    `import type { Recipe, Word } from "../types";\n\nexport const ID = ${JSON.stringify(pascal)};\nexport const VO_DURATION: number | undefined = ${vo ?? "undefined"};\n` +
    `export const RECIPE: Recipe = ${JSON.stringify(recipe, null, 1)};\nexport const WORDS: Word[] = ${JSON.stringify(words)};\nexport const AMP: number[] = ${JSON.stringify(amp)};\n`);
  const gens = check ? [] : readdirSync(join(ROOT, "src/storytime/gen")).filter((f) => f.endsWith(".story.gen.ts")).sort();
  wf(join(ROOT, "src/storytime/registry.gen.ts"),
    `// generated by tools/storytime_build.mjs; do not edit (lists src/storytime/gen/*.story.gen.ts)\nimport type { Recipe, Word } from "./types";\n` +
    gens.map((f, i) => `import * as S${i} from "./gen/${f.replace(/\.ts$/, "")}";`).join("\n") +
    `\n\nexport const STORY_RECIPES: { id: string; recipe: Recipe; words: Word[]; vo?: number; amp: number[] }[] = [\n` +
    gens.map((_, i) => `  { id: S${i}.ID, recipe: S${i}.RECIPE, words: S${i}.WORDS, vo: S${i}.VO_DURATION, amp: S${i}.AMP },`).join("\n") + `\n];\n`);
  if (!check) console.log(`wrote src/storytime/gen/${us}.story.gen.ts and the registry (${gens.length} recipe(s)); composition ${pascal} in src/index.storytime.ts`);

  // ---------------------------------------------------------------- 2) compile in node
  const stub = { name: "stub", setup(b) {
    b.onResolve({ filter: /^(remotion|@remotion\/.*|@react-three\/.*)$/ }, (a) => ({ path: a.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "const P=new Proxy(function(){return P},{get:(t,k)=>k==='__esModule'?false:P,apply:()=>P,construct:()=>P}); module.exports=P;", loader: "js" }));
  } };
  const r = await build({ entryPoints: [join(ROOT, "tools/storytime_entry.ts")], bundle: true, write: false, format: "esm", platform: "node", plugins: [stub], jsx: "automatic", logLevel: "error" });
  mkdirSync(join(ROOT, "out/tmp"), { recursive: true });
  const bundleF = join(ROOT, "out/tmp/storytime_build.bundle.mjs");
  writeFileSync(bundleF, r.outputFiles[0].text);
  const m = await import(pathToFileURL(bundleF).href + "?" + Date.now());
  let C;
  try { C = m.compileStory(recipe, words, vo, amp); } catch (e) { console.error(`COMPILE ERROR: ${e.message}`); return 1; }
  const dur = C.duration / 30;
  console.log(`compiled ${C.shots.length} shots, ${dur.toFixed(2)} s (${C.duration} frames, 1080x1920, 30 fps), ${C.chunks.length} caption chunks, black from ${C.endAt.toFixed(2)} s`);
  if (noQa) return 0;

  // ---------------------------------------------------------------- 3) 3D clip QA (every frame)
  const ov = (a, b) => [0, 1, 2].every((k) => Math.abs(a.c[k] - b.c[k]) < a.h[k] + b.h[k]);
  const clips = new Map();
  for (let f = 0; f < C.duration; f++) {
    const t = f / 30; if (t >= C.endAt) break;
    const s = C.shotAt(t);
    const leads = C.figsAt(t, s).filter((x) => x.lead).map((x) => ({ id: x.id, b: m.kidBoxes(x) }));
    const [A, B] = leads;
    for (const pa of ["head", "torso"]) for (const pb of ["head", "torso"]) if (ov(A.b[pa], B.b[pb]) && !clips.has(`${s.id} me.${pa} x homie.${pb}`)) clips.set(`${s.id} me.${pa} x homie.${pb}`, t);
    for (const L of leads) for (const bl of m.SETS[s.set].blockers) for (const p of ["head", "torso"]) if (ov(L.b[p], bl) && !clips.has(`${s.id} ${L.id}.${p} x ${bl.name}`)) clips.set(`${s.id} ${L.id}.${p} x ${bl.name}`, t);
  }
  const clipLines = [...clips].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(2)} s`);

  // ---------------------------------------------------------------- 4) framing R1-R6 (screen space, every frame)
  const capLines = (c, y, t) => {
    const sc = m.capPop(t, c.start, c.shout), fs = c.fs * sc, lh = fs * m.CAP.lineH, st = m.CAP.stroke * sc;
    // the real line box: the words as shown (not upper-cased unless they are)
    const w = m.textEm(c.text) * fs;
    return [{ x0: 540 - w / 2 - st, x1: 540 + w / 2 + st, y0: y - lh / 2 - st, y1: y + lh / 2 + st, text: c.text }];
  };
  const sample = (t) => {
    if (t >= C.endAt) return null;
    const s = C.shotAt(t), cam = C.camAt(t), named = C.named(s);
    const actors = C.figsAt(t, s).map((st) => {
      const b = m.kidBoxes(st);
      return { id: st.id, named: st.lead && named.includes(st.id), extra: "hair", yaw: st.yaw + st.headYaw, head: { ...b.head, yaw: st.yaw + st.headYaw }, face: { ...b.face, yaw: st.yaw + st.headYaw }, parts: [{ ...b.torso, yaw: st.yaw }] };
    });
    const cap = C.capAt(t);
    return {
      shot: s.id, views: [{ cam, left: 0, top: 0, w: 1080, h: 1920, name: "frame", face: s.cam.face ?? 0.34 }], actors,
      subjects: named.map((id) => ({ id, view: 0, why: "camera target" })), boards: [], props: [], cards: [],
      caption: cap ? { text: cap.chunk.text, lines: capLines(cap.chunk, cap.y, t) } : null,
    };
  };
  const c0 = C.capAt(0);
  const KF = kitFraming({ C, W: 1080, H: 1920, times: Array.from({ length: C.duration }, (_, f) => f / 30), sample, frame0: { hookPx: c0 ? c0.chunk.fs : 0, hookMinPx: 96, hookLabel: "the frame-0 shout caption (CAP.fsShout)" }, boardsAll: [] });
  console.log(KF.console);
  for (const l of KF.fq.lines) console.log("  " + l);

  // ---------------------------------------------------------------- 5) storytime rules
  const shots = C.shots;
  const lens = shots.map((s) => ({ id: s.id, d: s.b - s.a, hold: !!s.spec.hold, p: s.cam.preset }));
  const long = lens.filter((x) => x.d > 3.0 + 1e-6 && !x.hold);
  const shortSh = lens.filter((x) => x.d < 0.4);
  const avg = lens.reduce((a, x) => a + x.d, 0) / lens.length;
  const wideT = lens.filter((x) => x.p === "wide_class").reduce((a, x) => a + x.d, 0);
  const faceT = lens.filter((x) => /closeup|punch_in|ots/.test(x.p)).reduce((a, x) => a + x.d, 0);
  const cutT = Math.min(dur, C.endAt);
  const chunkBad = C.chunks.filter((c) => c.words.length < 1 || c.words.length > 3);
  const accBad = C.chunks.filter((c) => c.words.filter((w) => w.accent).length !== 1);
  const fitBad = C.chunks.filter((c) => !c.fitOk);
  const shoutBad = C.chunks.filter((c) => c.shout && c.text !== c.text.toUpperCase());
  const minFs = Math.min(...C.chunks.map((c) => c.fs));
  // mouths: only the speaker's mouth moves with the voice
  let wrongMouth = 0, talkFrames = 0;
  for (let f = 0; f < C.duration; f++) {
    const t = f / 30; if (t >= C.endAt) break;
    const sp = C.speakerAt(t);
    for (const id of ["me", "homie"]) { const mo = C.mouthOf(id, t); if (mo > 0.01 && (!sp || sp.speaker !== id)) wrongMouth++; if (mo > 0.05) talkFrames++; }
  }
  const lastOn = Math.floor(C.endAt * 30 - 1e-6);
  const f0 = shots[0].cam.preset;
  const firstCut = shots[1]?.a ?? dur;
  const shakes = shots.flatMap((s) => s.fx.filter((x) => x.fx === "shake").map(() => s.id));
  const shout = Object.entries(recipe.lines).filter(([, L]) => L.shout).map(([k]) => Number(k));
  const shoutShots = shout.map((ln) => { const sp = C.spans.find((x) => x.line === ln); const ss = shots.filter((s) => s.a < sp.b && s.b > sp.a); return { ln, punch: ss.some((s) => s.cam.preset === "punch_in"), shake: ss.some((s) => s.fx.some((x) => x.fx === "shake")) }; });
  const shatter = shots.some((s) => s.set === "cafeteria" && s.fx.some((x) => x.fx === "shatter"));
  const gate = [
    ["first spoken word by 0.2 s", words[0].t <= 0.2, `${words[0].w} at ${words[0].t.toFixed(2)} s`, true],
    ["frame 0 is a face close-up (closeup / punch_in)", /closeup|punch_in/.test(f0), f0, true],
    ["first cut by 1.25 s", firstCut <= 1.25, `${firstCut.toFixed(2)} s`, true],
    ["a cut every 1-3 s: no shot over 3.0 s unless hold: true", long.length === 0, long.length ? long.map((x) => `${x.id} ${x.d.toFixed(2)} s`).join(", ") : `longest ${Math.max(...lens.filter((x) => !x.hold).map((x) => x.d)).toFixed(2)} s; average ${avg.toFixed(2)} s over ${lens.length} shots`, true],
    ["no flash cuts under 0.4 s", shortSh.length === 0, shortSh.map((x) => `${x.id} ${x.d.toFixed(2)} s`).join(", ") || "none", false],
    ["almost no wides: wide_class <= 10 % of the runtime", wideT <= 0.1 * cutT, `${(100 * wideT / cutT).toFixed(1)} %`, true],
    ["face shots (close-up, punch-in, OTS) >= 60 % of the runtime", faceT >= 0.6 * cutT, `${(100 * faceT / cutT).toFixed(1)} %`, false],
    ["captions: 1-3 words per chunk", chunkBad.length === 0, chunkBad.map((c) => c.text).join(" | ") || `${C.chunks.length} chunks`, true],
    ["captions: exactly one yellow accent word per chunk", accBad.length === 0, accBad.map((c) => c.text).join(" | ") || "all", true],
    ["captions: shout lines ALL CAPS", shoutBad.length === 0, shoutBad.map((c) => c.text).join(" | ") || `lines ${shout.join(", ")}`, true],
    [`captions text-fit: every chunk on one line at >= ${m.CAP.minFs} px`, fitBad.length === 0, fitBad.map((c) => `"${c.text}" ${c.fs} px`).join(", ") || `smallest ${minFs.toFixed(1)} px`, true],
    ["shouts get a punch-in and a shake", shoutShots.every((x) => x.punch && x.shake), shoutShots.map((x) => `line ${x.ln}: ${x.punch ? "punch" : "NO punch"}/${x.shake ? "shake" : "NO shake"}`).join(", "), false],
    ["mouths: only the speaking character's mouth moves", wrongMouth === 0, `${wrongMouth} wrong frame(s); ${talkFrames} talking kid-frames`, true],
    ["the cafeteria windows shatter", shatter, shatter ? "yes" : "no shatter fx in a cafeteria shot", false],
    ["hard cut to black (no fade) at the end", Number.isFinite(C.endAt) && C.endAt < dur, Number.isFinite(C.endAt) ? `last picture frame ${lastOn}, black from frame ${lastOn + 1} (${C.endAt.toFixed(2)} s) to ${C.duration - 1}` : "recipe.end not set", true],
    ["1080x1920, plain 30 fps, no motion blur", true, "one composition, no Sub", true],
    ["length 30-90 s", dur >= 30 && dur <= 90, `${dur.toFixed(2)} s`, false],
  ];
  gate.push(...KF.rows);
  const hard = gate.some((g) => g[3] && !g[1]);
  const rep = [
    `# ${slug}: storytime recipe QA (tools/storytime_build.mjs)`, "",
    `Composition \`${pascal}\` in \`src/index.storytime.ts\` (1080x1920, 30 fps, no motion blur). ${shots.length} shots, ${dur.toFixed(2)} s, black from ${C.endAt.toFixed(2)} s.`, "",
    `## 3D clip QA: ${clips.size} clip(s)`, "", ...(clipLines.length ? clipLines.map((l) => `- ${l}`) : ["- none: the two leads never intersect each other or a set blocker."]), "",
    ...KF.fr.md,
    "## Gate", "", "| check | result | detail |", "|---|---|---|", ...gate.map(([k, ok, d, h]) => `| ${k} | ${ok ? "PASS" : h ? "**FAIL**" : "warn"} | ${d} |`), "",
    "## Shots", "", "| shot | start | len | set | camera | note |", "|---|---|---|---|---|---|",
    ...shots.map((s) => `| ${s.id} | ${s.a.toFixed(2)} | ${(s.b - s.a).toFixed(2)} | ${s.set} | ${s.cam.preset}${s.cam.on && !/closeup_/.test(s.cam.preset) ? ` (${s.on})` : ""} | ${s.spec.note ?? ""} |`), "",
    "## Captions", "", ...C.chunks.map((c) => `- ${c.start.toFixed(2)} s: ${c.words.map((w) => (w.accent ? `**${w.text}**` : w.text)).join(" ")} (${c.fs.toFixed(0)} px${c.shout ? ", shout" : ""})`), "",
  ];
  wf(join(dir, "RECIPE_QA.md"), rep.join("\n"));
  for (const l of clipLines) console.log(l);
  for (const [k, ok, d, h] of gate) console.log(`${ok ? "PASS" : h ? "FAIL" : "warn"}  ${k}: ${d}`);
  console.log(`total ${((Date.now() - T0) / 1000).toFixed(1)} s${check ? "" : `; report ${join(dir, "RECIPE_QA.md")}`}`);
  return clips.size || hard ? 1 : 0;
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(await main(process.argv.slice(2)));
