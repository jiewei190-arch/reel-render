// cyber_build.mjs: a cyber3d recipe ("kit": "cyber3d") -> a Remotion composition, then the clip QA, the frame-0 gate
// and the kit rules (text placement, flash safety, story devices).
//   node tools/cyber_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>]
//   (node tools/recipe_build.mjs <slug> forwards here when recipe.json says "kit": "cyber3d")
// Reads   <shorts>/<slug>/recipe.json + vo/timings.json
// Writes  src/cyber/gen/<slug_>.cyber.gen.ts    the recipe + word timings as a TS module
//         src/cyber/registry.gen.ts             every *.cyber.gen.ts (CyberRoot registers <Pascal>Recipe)
//         out/tmp/<slug>.cues.json              the audio plan (STORY_CUES=<file> python tools/story_mix.py ...)
//         <shorts>/<slug>/RECIPE_QA.md          the QA + gate report
// Nothing here touches the Block Money or tech3d registries.
import { build } from "esbuild";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const main = async (argv) => {
  const args = argv.slice();
  const slug = args.find((a) => !a.startsWith("--") && !/^\//.test(a) && args[args.indexOf(a) - 1] !== "--shorts");
  if (!slug || !/^[a-z0-9-]+$/.test(slug)) { console.error("usage: node tools/cyber_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>]"); return 2; }
  const si = args.indexOf("--shorts");
  const SHORTS = si >= 0 ? resolve(args[si + 1]) : resolve(ROOT, "../shorts");
  const noQa = args.includes("--no-qa"), check = args.includes("--check");
  const dir = join(SHORTS, slug);
  const recipe = JSON.parse(readFileSync(join(dir, "recipe.json"), "utf8"));
  const timings = JSON.parse(readFileSync(join(dir, "vo/timings.json"), "utf8"));
  if (recipe.slug !== slug) { console.error(`recipe.slug "${recipe.slug}" != folder "${slug}"`); return 2; }
  if (recipe.kit !== "cyber3d") { console.error(`recipe.kit is "${recipe.kit}", not "cyber3d"`); return 2; }

  // ---------------------------------------------------------------- 1) codegen
  const wf = (f, txt) => { if (!check) writeFileSync(f, txt); };
  const us = slug.replace(/-/g, "_");
  const pascal = slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("") + "Recipe";
  const words = timings.turns.flatMap((tn) => tn.words.map((w) => ({ w: w.w, turn: tn.turn, t: w.t, end: w.end })));
  const vo = timings.source?.duration;
  mkdirSync(join(ROOT, "src/cyber/gen"), { recursive: true });
  wf(join(ROOT, `src/cyber/gen/${us}.cyber.gen.ts`),
    `// generated by tools/cyber_build.mjs from finance/shorts/${slug}/recipe.json + vo/timings.json; do not edit\n` +
    `import type { Word } from "../../fin/recipe/types";\nimport type { CyberRecipe } from "../types";\n\n` +
    `export const ID = ${JSON.stringify(pascal)};\nexport const VO_DURATION: number | undefined = ${vo === undefined ? "undefined" : vo};\n` +
    `export const RECIPE: CyberRecipe = ${JSON.stringify(recipe, null, 1)};\n` +
    `export const WORDS: Word[] = ${JSON.stringify(words)};\n`);
  const gens = check ? [] : readdirSync(join(ROOT, "src/cyber/gen")).filter((f) => f.endsWith(".cyber.gen.ts")).sort();
  wf(join(ROOT, "src/cyber/registry.gen.ts"),
    `// generated by tools/cyber_build.mjs; do not edit (lists src/cyber/gen/*.cyber.gen.ts)\nimport type { Word } from "../fin/recipe/types";\nimport type { CyberRecipe } from "./types";\n` +
    gens.map((f, i) => `import * as C${i} from "./gen/${f.replace(/\.ts$/, "")}";`).join("\n") +
    `\n\nexport const CYBER_RECIPES: { id: string; recipe: CyberRecipe; words: Word[]; vo?: number }[] = [\n` +
    gens.map((_, i) => `  { id: C${i}.ID, recipe: C${i}.RECIPE, words: C${i}.WORDS, vo: C${i}.VO_DURATION },`).join("\n") + `\n];\n`);
  if (!check) console.log(`wrote src/cyber/gen/${us}.cyber.gen.ts and the cyber registry (${gens.length} recipe(s)); composition ${pascal} in src/index.cyber.ts`);

  // ---------------------------------------------------------------- 2) compile in node
  const stub = { name: "stub", setup(b) {
    b.onResolve({ filter: /^(remotion|@remotion\/.*|@react-three\/.*)$/ }, (a) => ({ path: a.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "const P=new Proxy(function(){return P},{get:(t,k)=>k==='__esModule'?false:P,apply:()=>P,construct:()=>P}); module.exports=P;", loader: "js" }));
  } };
  const r = await build({ entryPoints: [join(ROOT, "tools/cyber_entry.ts")], bundle: true, write: false, format: "esm", platform: "node", plugins: [stub], jsx: "automatic", logLevel: "error" });
  mkdirSync(join(ROOT, "out/tmp"), { recursive: true });
  const bundleF = join(ROOT, "out/tmp/cyber_build.bundle.mjs");
  writeFileSync(bundleF, r.outputFiles[0].text);
  const m = await import(pathToFileURL(bundleF).href + "?" + Date.now());
  let C;
  try { C = m.compileCyber(recipe, words, vo); } catch (e) { console.error(`COMPILE ERROR: ${e.message}`); return 1; }
  let landscapeErr = null;
  try { m.compileCyber({ ...recipe, frame: "landscape" }, words, vo); } catch (e) { landscapeErr = e.message; }
  const L = C.L;
  const dur = C.duration / 30;
  writeFileSync(join(ROOT, `out/tmp/${slug}.cues.json`), JSON.stringify({ [pascal]: { music: C.audio.music, musicDb: -12, cues: C.audio.cues, duration: dur, cuts: C.shots.map((s) => s.a) } }));
  console.log(`compiled ${C.shots.length} shots, ${dur.toFixed(2)} s (${C.duration} frames), ${C.audio.cues.length} sfx cues, frame ${L.id} ${L.W}x${L.H}`);
  if (noQa) return 0;

  // ---------------------------------------------------------------- 3) clip QA (every frame x 4 sub-frames)
  const ov = (p, a) => [0, 1, 2].every((k) => Math.abs(p.c[k] - a.c[k]) < p.h[k] + a.h[k]);
  const hits = new Map();
  const note = (k, t) => { if (!hits.has(k)) hits.set(k, t); };
  for (let f = 0; f < C.duration * 4; f++) {
    const t = f / 120;
    const { bolts, props } = C.qa(t);
    const sid = C.shotAt(t).id;
    for (const b of bolts) {
      if (b.c[1] - b.h[1] < -0.01) note(`${sid} ${b.name} below the ground`, t);
      for (const p of props) if (ov(p, b)) note(`${sid} ${p.name} x ${b.name}`, t);
    }
    for (const s of C.shotAt(t).props) {
      if (!s.def || !s.def.grounded || s.spec.motion === "path" || t < s.a || t >= s.b) continue;
      for (const p of props) if (p.name.startsWith(`${s.key}.`) && p.c[1] - p.h[1] < -0.05) note(`${sid} ${p.name} below the floor`, t);
    }
  }
  const qaLines = [...hits].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(3)} s (frame ${Math.floor(t * 30)})`);

  // ---------------------------------------------------------------- 4) gate
  const sub3 = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
  const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
  const crs = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
  const nrm = (a) => { const l = Math.hypot(...a) || 1; return a.map((x) => x / l); };
  const coverage = (cam, b) => {
    const f = nrm(sub3(cam.look, cam.pos)), rgt = nrm(crs(f, [0, 1, 0])), up = crs(rgt, f), th = Math.tan((cam.fov * Math.PI) / 360), asp = L.W / L.H;
    let y0 = Infinity, y1 = -Infinity, x0 = Infinity, x1 = -Infinity;
    for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) {
      const p = [b.c[0] + sx * b.h[0], b.c[1] + sy * b.h[1], b.c[2] + sz * b.h[2]];
      const d = sub3(p, cam.pos), z = dot(d, f);
      if (z <= 0.05) return 0;
      const ny = dot(d, up) / (z * th), nx = dot(d, rgt) / (z * th * asp);
      y0 = Math.min(y0, ny); y1 = Math.max(y1, ny); x0 = Math.min(x0, nx); x1 = Math.max(x1, nx);
    }
    if (x1 < -1 || x0 > 1) return 0;
    return Math.max(0, Math.min(1, y1) - Math.max(-1, y0)) / 2;
  };
  const cam0 = C.camAt(0);
  const subjects = [];
  for (const st of C.boltsAt(0)) subjects.push({ name: st.id, who: true, c: [st.x, st.y + 0.12 * st.s, st.z], h: [0.4 * st.s, 0.45 * st.s, 0.35 * st.s] });
  for (const fg of C.figuresAt(0)) { const [body] = m.figureBoxes(fg.key, fg.p, fg.yaw, fg.s, fg.rig); subjects.push({ name: fg.key, who: true, c: body.c, h: body.h }); }
  for (const p of C.shotAt(0).props) if (p.def) { const b = m.objBox(p.def, C.placeOf(p, 0)); subjects.push({ name: p.key, c: b.c, h: b.h }); }
  const covs = subjects.map((b) => ({ name: b.name, who: !!b.who, k: coverage(cam0, b) })).sort((a, b) => b.k - a.k);
  const best = covs[0] ?? { name: "nothing", k: 0 };
  const hookText = recipe.hook.text;
  const hookWords = hookText.replace(/\*/g, "").trim().split(/\s+/).length;
  const HB = m.hookBox(hookText, L);
  const orange = hookText.match(/\*[^*]+\*/g) ?? [];
  const line1 = words.filter((w) => w.turn === 1).map((w) => w.w).join(" ");
  const stake = /\$\s?\d/;
  let stakeAt = null;
  for (let f = 0; f <= 15 && stakeAt === null; f++) if (C.textsAt(f / 30).some((s) => stake.test(s))) stakeAt = f / 30;
  const hasBolt = C.shots.some((s) => s.bolts.length);
  const face0 = new Map(C.boltsAt(0).map((b) => [b.id, b.face]));
  let faceAt = null;
  if (face0.size) for (let f = 1; f <= 45 && faceAt === null; f++) for (const b of C.boltsAt(f / 30)) if (!face0.has(b.id) || face0.get(b.id) !== b.face) { faceAt = f / 30; break; }
  const PUNCH = /^(impact|drop|crash|boom|thud|punch|stamp|coins|scratch|paper|rip|alarm)/;
  const sfx0 = C.audio.cues.filter((c) => c.t <= 0.02);
  const moves = new Set();
  for (const s of C.shots) { if (s.a > 0 && s.a <= 3.0) moves.add(`cut ${s.a.toFixed(2)}`); for (const [t] of s.kicks) if (t <= 3.0 && t > 0.05) moves.add(`hit ${t.toFixed(2)}`); }
  const early = C.shots.filter((s) => s.a < 1.0);
  const whoAt0 = covs.filter((c) => c.who && c.k >= 0.15);
  // faces that text must avoid: BOLT's screen and the figure's hood
  const band = [L.cap.centre - L.cap.band, L.cap.centre + L.cap.band];
  const faceRects = (cam, t) => {
    const out = [];
    for (const st of C.boltsAt(t)) { const f = m.boltFace(st); const q = m.project(cam, f.c, L); if (q && q.x > -100 && q.x < L.W + 100) { const r = f.r * q.k; out.push({ x: q.x, y: q.y, w: 2 * r, h: 2 * r, who: st.id }); } }
    for (const fg of C.figuresAt(t)) { const [, head] = m.figureBoxes(fg.key, fg.p, fg.yaw, fg.s, fg.rig); const q = m.project(cam, head.c, L); if (q && q.x > -100 && q.x < L.W + 100 && q.z > 0.3) { const r = 0.15 * q.k; out.push({ x: q.x, y: q.y, w: 2 * r, h: 2 * r, who: fg.key }); } }
    return out;
  };
  const hitR = (a, b) => Math.abs(a.x - b.x) * 2 < a.w + b.w && Math.abs(a.y - b.y) * 2 < a.h + b.h;
  let capT = 0, capOk = 0;
  const capBad = new Set(), labelFace = new Set(), labelBand = new Set(), staticF = [], hookFace = new Set(), labelBoard = new Set(), devBand = new Set(), devFace = new Set();
  let prevCam = null;
  for (let f = 0; f < C.duration; f++) {
    const t = f / 30, s = C.shotAt(t), cam = C.camAt(t);
    if (prevCam && C.shotAt((f - 1) / 30) === s) {
      const d = Math.hypot(...sub3(cam.pos, prevCam.pos)) + Math.hypot(...sub3(cam.look, prevCam.look)) + Math.abs(cam.fov - prevCam.fov) * 0.01 + Math.abs((cam.roll ?? 0) - (prevCam.roll ?? 0)) * 0.01;
      if (d < 2e-4) staticF.push(f);
    }
    prevCam = cam;
    const faces = faceRects(cam, t);
    const capOn = t >= L.cap.from && recipe.captions !== "off" && s.spec.caption !== "off";
    if (capOn) { capT++; if (faces.every((r) => r.y + r.h / 2 < band[0] || r.y - r.h / 2 > band[1])) capOk++; else capBad.add(s.id); }
    const labs = C.labelsAt(t).filter((l) => l.u >= 0.3), bds = C.boardsAt(t).filter((b) => b.u >= 0.3), devs = C.devicesAt(t).filter((d) => d.u >= 0.3 && d.kind !== "alert");
    for (const l of labs) { if (faces.some((r) => hitR(l, r))) labelFace.add(`${l.text}@${t.toFixed(1)}s`); if (l.y + l.h / 2 > band[0] - 1) labelBand.add(l.text); }
    for (const b of bds) if (faces.some((r) => hitR(b, r))) labelFace.add(`board ${b.title}@${t.toFixed(1)}s`);
    for (const d of devs) { if (d.y + d.h / 2 > band[0] - 1) devBand.add(d.kind); if (faces.some((r) => hitR(d, r))) devFace.add(`${d.kind}@${t.toFixed(1)}s`); }
    for (const l of labs) for (const b of [...bds, ...devs]) if (hitR(l, b)) labelBoard.add(`${l.text}/${b.title ?? b.kind}@${t.toFixed(1)}s`);
    if (t <= C.hookUntil || (C.hookAgain !== null && t >= C.hookAgain)) for (const r of faces) if (hitR(HB, r)) hookFace.add(`${s.id} ${r.who}@${t.toFixed(1)}s`);
  }
  const capShare = capT ? capOk / capT : 1;
  const oneAtATime = [];
  for (const s of C.shots) { const ts = s.labels.map((l) => l.t0).sort((a, b) => a - b); for (let i = 1; i < ts.length; i++) if (ts[i] - ts[i - 1] < 0.3) oneAtATime.push(`${s.id} ${ts[i - 1].toFixed(2)}/${ts[i].toFixed(2)} s`); }
  const nLabels = C.shots.reduce((n, s) => n + s.labels.length, 0);
  const firstCut = C.shots.length > 1 ? C.shots[1].a : dur;
  const lastShot = C.shots[C.shots.length - 1], firstShot = C.shots[0];
  const loopy = C.hookAgain !== null && JSON.stringify(lastShot.spec.cam.target) === JSON.stringify(firstShot.spec.cam.target);
  // flash safety: no more than 2 full-frame events (glitch / alert) in any 1 s, peaks capped, never a white flash
  let worstWin = 0, worstAt = 0;
  for (const e of C.flashes) { const n = C.flashes.filter((x) => x.t0 >= e.t0 && x.t0 < e.t0 + 1).length; if (n > worstWin) { worstWin = n; worstAt = e.t0; } }
  const peakG = Math.max(0, ...C.flashes.filter((x) => x.kind === "glitch").map((x) => x.peak)), peakA = Math.max(0, ...C.flashes.filter((x) => x.kind === "alert").map((x) => x.peak));
  const minFs = Math.min(L.label.fs, L.cap.fs, L.hook.fs);
  const nCase = (recipe.caseFile ?? []).length, ck = recipe.checklist;
  const ckLate = ck ? C.at(ck.at) >= dur * 0.6 : false;
  const fmt = recipe.format ?? "short";
  const lenOk = fmt === "long" ? dur >= 300 && dur <= 480 : dur >= 30 && dur <= 55;
  const gate = [
    ["frame 0 is close: a subject covers >= 50 % of the frame height", best.k >= 0.5, `${best.name} ${(best.k * 100).toFixed(0)} %`, true],
    ["hook at frame 0: <= 5 words, <= 2 lines that fit, exactly one *neon* word", C.hookUntil > 0 && hookWords <= 5 && HB.lines.length <= 2 && HB.textW <= L.hook.maxW && orange.length === 1, `"${hookText}" (${hookWords} words, ${HB.lines.length} line(s), widest ~${HB.textW.toFixed(0)} px of ${L.hook.maxW}, neon: ${orange.join(" ") || "none"}, until ${C.hookUntil.toFixed(2)} s)`, true],
    ["the dollar stake: line 1 says it, and a $ figure is on screen by 0.5 s", stake.test(line1) && stakeAt !== null, `line 1 "${line1}"; on screen ${stakeAt === null ? "not by 0.5 s" : `at ${stakeAt.toFixed(2)} s`}`, true],
    ["who at frame 0 (the figure or BOLT >= 15 % of the height)", whoAt0.length > 0, whoAt0.map((c) => `${c.name} ${(c.k * 100).toFixed(0)} %`).join(", ") || "none", true],
    ["first spoken word by 0.2 s", words[0].t <= 0.2, `${words[0].w} at ${words[0].t.toFixed(2)} s`, true],
    ["a sound punch at 0.00 s", sfx0.some((c) => PUNCH.test(c.sfx)), sfx0.map((c) => c.sfx).join(", ") || "none", true],
    ["2-3 cuts or big moves in the first 3 s", moves.size >= 2, [...moves].join(", ") || "none", true],
    ["music + an SFX at frame 0", !!C.audio.music && C.audio.cues.some((c) => c.t <= 0.05), `${C.audio.music}, ${C.audio.cues.filter((c) => c.t <= 0.05).map((c) => c.sfx).join(", ")}`, true],
    ["no wide shot in the first 1 s", early.every((s) => s.spec.cam.preset !== "wide"), early.map((s) => `${s.id} ${s.spec.cam.preset}`).join(", "), true],
    ["frame-0 shot cuts away by ~1.0 s (first cut <= 1.25 s)", firstCut <= 1.25, `first cut at ${firstCut.toFixed(2)} s`, true],
    ["faces (BOLT's screen, the figure's hood) clear of the caption band >= 90 % of caption time", capShare >= 0.9, `${(capShare * 100).toFixed(0)} %${capBad.size ? `; in the band in ${[...capBad].join(", ")}` : ""}`, true],
    ["labels: <= 3 words (compile-enforced), one at a time (>= 0.3 s apart)", oneAtATime.length === 0, `${nLabels} label(s)${oneAtATime.length ? `; too close: ${oneAtATime.join(", ")}` : ""}`, true],
    ["text off faces: no label, board or device card over a face", labelFace.size === 0 && devFace.size === 0, [...labelFace, ...devFace].slice(0, 6).join(", ") || "none", true],
    ["the hook card never covers a face", hookFace.size === 0, [...hookFace].slice(0, 6).join(", ") || "clear", true],
    ["label cards never overlap a board or a story card", labelBoard.size === 0, [...labelBoard].slice(0, 6).join(", ") || "none", true],
    ["labels and story cards above the caption band", labelBand.size === 0 && devBand.size === 0, [...labelBand, ...devBand].join(", ") || "all above", true],
    ["no static frames: the camera moves on every frame", staticF.length === 0, staticF.length ? `${staticF.length} still frame(s), first ${staticF.slice(0, 5).join(", ")}` : "moves on every frame", true],
    ["flash safety: <= 2 glitch/alert events in any 1 s, glitch <= 0.6, alert wash <= 0.35, no white flash", worstWin <= 2 && peakG <= 0.6 && peakA <= 0.35, `${C.flashes.length} event(s), worst ${worstWin} in 1 s (at ${worstAt.toFixed(2)} s); peaks glitch ${peakG}, alert ${peakA}`, true],
    ["text readable at phone size (smallest kit type >= 40 px in a 1080-wide frame)", minFs >= 40 * L.k, `label ${L.label.fs}, caption ${L.cap.fs}, hook ${L.hook.fs} px`, true],
    ["the landscape layout compiles too (1920x1080)", landscapeErr === null, landscapeErr ?? "ok", true],
    ["story: a CASE FILE card, and the HOW TO SPOT IT checklist in the last 40 %", nCase > 0 && !!ck && ckLate, `case files ${nCase}; checklist ${ck ? `at ${C.at(ck.at).toFixed(2)} s (${ck.items.length} items)` : "none"}`, false],
    ["BOLT (optional narrator) changes face within 1.5 s of frame 0 when on screen at 0", face0.size === 0 || faceAt !== null, !hasBolt ? "no BOLT" : face0.size === 0 ? "BOLT not at frame 0" : faceAt === null ? "no change" : `at ${faceAt.toFixed(2)} s`, false],
    ["loop ending: the hook comes back and the last shot frames the first shot's subject", loopy, `hook again ${C.hookAgain === null ? "not set" : `at ${C.hookAgain.toFixed(2)} s`}; last target ${JSON.stringify(lastShot.spec.cam.target)}`, false],
    [fmt === "long" ? "length 5-8 min" : "length 30-55 s", lenOk, `${dur.toFixed(2)} s`, false],
  ];
  const hardFail = gate.some((g) => g[3] && !g[1]);
  const rep = [
    `# ${slug}: cyber3d recipe QA (tools/cyber_build.mjs)`, "",
    `Composition: \`${pascal}\` in \`src/index.cyber.ts\` (plain 30 fps). Kit cyber3d, format ${fmt}, frame ${L.id} ${L.W}x${L.H}. ${C.shots.length} shots, ${dur.toFixed(2)} s.`, "",
    `## Clip QA: ${C.duration} frames x 4 sub-frames, ${hits.size} clip(s)`, "",
    ...(qaLines.length ? qaLines.map((l) => `- ${l}`) : ["- none: no part, figure, kit prop or set piece enters BOLT's shell or mitts; BOLT stays above the ground; grounded objects stay above the floor."]), "",
    `## Frame-0 gate and kit rules`, "", "| check | result | detail |", "|---|---|---|",
    ...gate.map(([k, ok, d, hard]) => `| ${k} | ${ok ? "PASS" : hard ? "**FAIL**" : "warn"} | ${String(d).replace(/\|/g, "/")} |`), "",
    `Frame-0 coverage by subject: ${covs.slice(0, 5).map((c) => `${c.name} ${(c.k * 100).toFixed(0)} %`).join(", ") || "none"}.`, "",
  ];
  wf(join(dir, "RECIPE_QA.md"), rep.join("\n"));
  console.log(`clip QA: ${hits.size} clip(s)`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}`);
  return hits.size || hardFail ? 1 : 0;
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) process.exit(await main(process.argv.slice(2)));
