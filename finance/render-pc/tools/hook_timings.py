"""hook_timings.py <A.json> <B.json> <C.json> [--tail 0.6]

Rewrites src/shorts/hooks.timings.gen.ts from three Whisper timings.json files (format: {"source": {"duration"},
"turns": [{"words": [{"w", "t", "end"}]}]}, or a flat {"words": [...]}). duration = last word end + tail, but never
shorter than the voice file itself.
"""
import json
import os
import sys

args = [a for a in sys.argv[1:] if not a.startswith("--")]
tail = 0.6
if "--tail" in sys.argv:
    tail = float(sys.argv[sys.argv.index("--tail") + 1])
    args = [a for a in args if a != str(tail) and a != sys.argv[sys.argv.index("--tail") + 1]]
out = {}
for h, p in zip("ABC", args[:3]):
    d = json.load(open(p, encoding="utf-8"))
    raw = [w for turn in d["turns"] for w in turn["words"]] if "turns" in d else d["words"]
    words = [{"w": w["w"].strip(), "a": round(float(w.get("t", w.get("start", 0))), 3), "b": round(float(w.get("end", 0)), 3)} for w in raw if w["w"].strip()]
    dur = max(words[-1]["b"] + tail, float(d.get("source", {}).get("duration", 0)) + 0.2, 5.0)
    out[h] = {"words": words, "duration": round(dur, 2)}
    print(h, f"{len(words)} words, {dur:.2f} s:", " ".join(w["w"] for w in words))
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = "// generated by tools/hook_timings.py from the finance/hooks/{A,B,C} timings\n"
s += 'export type HookWord = { w: string; a: number; b: number };\nexport const HOOKS: Record<"A" | "B" | "C", { words: HookWord[]; duration: number }> = '
s += json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
open(os.path.join(root, "src", "shorts", "hooks.timings.gen.ts"), "w", encoding="utf-8").write(s)
