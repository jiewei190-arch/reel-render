"""hook_mix.py <A|B|C> <voice.wav> <audio_dir> <out_premix.wav>

Premix for a hook prototype: voice + a music bed ducked under the voice (sidechain) + SFX at the cues exported by
tools/hook_cues.mjs (one on every cut, plus the hook-word hit). Loudness is set afterwards by tools/mux_voice.sh
(-14 LUFS integrated, true peak <= -1.5 dBFS). audio_dir holds music/<name>.wav and sfx/<name>.wav (the toon3d
library: procedurally generated by its own gen_audio_assets.py, no third-party audio).
"""
import json
import os
import subprocess
import sys

h, voice, adir, out = sys.argv[1:5]
here = os.path.dirname(os.path.abspath(__file__))
info = json.loads(subprocess.check_output(["node", os.path.join(here, "hook_cues.mjs")], cwd=os.path.dirname(here)))[h]
dur = info["duration"]
music = os.path.join(adir, "music", info["music"] + ".wav")
ins = ["-i", voice, "-i", music]
parts = []
labels = []
for k, c in enumerate(sorted(info["cues"], key=lambda c: c["t"])):
    f = os.path.join(adir, "sfx", c["sfx"] + ".wav")
    if not os.path.exists(f):
        sys.exit(f"missing sfx {f}")
    ins += ["-i", f]
    j = len(ins) // 2 - 1
    ms = max(0, int(round(c["t"] * 1000)))
    parts.append(f"[{j}:a]aresample=48000,aformat=channel_layouts=stereo,volume={c.get('db', 0) - 6}dB,adelay={ms}|{ms}[s{k}]")
    labels.append(f"[s{k}]")
fc = [
    f"[0:a]aresample=48000,aformat=channel_layouts=stereo,apad=whole_dur={dur}[vo]",
    "[vo]asplit=2[vo1][key]",
    # the bed starts loud at frame 0 (no silent intro), then ducks ~10 dB under the voice
    f"[1:a]aresample=48000,aformat=channel_layouts=stereo,atrim=0:{dur},afade=t=out:st={max(0, dur - 0.35)}:d=0.35,volume=-12dB[mus]",
    "[mus][key]sidechaincompress=threshold=0.02:ratio=8:attack=8:release=220:makeup=1[bed]",
    *parts,
    f"[vo1][bed]{''.join(labels)}amix=inputs={2 + len(labels)}:normalize=0:duration=first,atrim=0:{dur}[mix]",
]
cmd = ["ffmpeg", "-v", "error", "-y", *ins, "-filter_complex", ";".join(fc), "-map", "[mix]", "-c:a", "pcm_s16le", "-ar", "48000", out]
subprocess.check_call(cmd)
print(f"premix {h}: {dur:.2f} s, music {info['music']}, {len(labels)} sfx, hook word at {info['hookWord']:.2f} s -> {out}")
