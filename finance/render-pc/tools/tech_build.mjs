// tech_build.mjs: a tech3d recipe ("kit": "tech3d") -> a Remotion composition, then the clip QA and the frame-0 gate.
//   node tools/tech_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>] [--qa-sample N]
//   (node tools/recipe_build.mjs <slug> forwards here when recipe.json says "kit": "tech3d")
// LONG-FORM ("format": "landscape", LONGFORM.md): the recipe may live in finance/longform/<slug>; the clip QA checks
// every Nth output frame (--qa-sample N), the long-form gate (tools/kit_long.mjs) replaces the Shorts frame-0 gate, and
// <dir>/chapters.txt is written. Shorts keep the full QA (every frame x 4 sub-frames) and their gate, unchanged.
// Reads   <shorts>/<slug>/recipe.json + vo/timings.json
// Writes  src/tech/gen/<slug_>.tech.gen.ts    the recipe + word timings as a TS module
//         src/tech/registry.gen.ts            every *.tech.gen.ts (TechRoot registers <Pascal>Recipe + <Pascal>RecipeSub)
//         out/tmp/<slug>.cues.json            the audio plan (STORY_CUES=<file> python tools/story_mix.py ...)
//         <shorts>/<slug>/RECIPE_QA.md        the QA + gate report
// Nothing here touches the Block Money registry (src/fin/recipe/registry.gen.ts) or src/index.toolkit.ts.
import { build } from "esbuild";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { chaptersTxt, kitArgs, kitLongGate, kitLongReport, qaTimes } from "./kit_long.mjs";
import { runFraming } from "./framing_kits.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const main = async (argv) => {
  const T0 = Date.now();
  const A = kitArgs(argv);
  if (A.err) { console.error(A.err === "usage" ? "usage: node tools/tech_build.mjs <slug> [--no-qa] [--check] [--shorts <dir>] [--qa-sample N]" : A.err); return 2; }
  const { slug, SHORTS, dir, noQa, check, qaSample, qaSampleGiven } = A;
  const recipe = JSON.parse(readFileSync(join(dir, "recipe.json"), "utf8"));
  const timings = JSON.parse(readFileSync(join(dir, "vo/timings.json"), "utf8"));
  if (recipe.slug !== slug) { console.error(`recipe.slug "${recipe.slug}" != folder "${slug}"`); return 2; }
  if (recipe.kit !== "tech3d") { console.error(`recipe.kit is "${recipe.kit}", not "tech3d": use tools/recipe_build.mjs`); return 2; }
  const LS = recipe.format === "landscape";
  if (!LS && qaSampleGiven) console.log("--qa-sample is for long-form only: a Short always gets the full QA (every frame x 4 sub-frames)");

  // ---------------------------------------------------------------- 1) codegen
  const wf = (f, txt) => { if (!check) writeFileSync(f, txt); };
  const us = slug.replace(/-/g, "_");
  const pascal = slug.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("") + "Recipe";
  const words = timings.turns.flatMap((tn) => tn.words.map((w) => ({ w: w.w, turn: tn.turn, t: w.t, end: w.end })));
  const vo = timings.source?.duration;
  mkdirSync(join(ROOT, "src/tech/gen"), { recursive: true });
  wf(join(ROOT, `src/tech/gen/${us}.tech.gen.ts`),
    `// generated by tools/tech_build.mjs from finance/${SHORTS.endsWith("/longform") ? "longform" : "shorts"}/${slug}/recipe.json + vo/timings.json; do not edit\n` +
    `import type { Word } from "../../fin/recipe/types";\nimport type { TechRecipe } from "../types";\n\n` +
    `export const ID = ${JSON.stringify(pascal)};\nexport const VO_DURATION: number | undefined = ${vo === undefined ? "undefined" : vo};\n` +
    `export const RECIPE: TechRecipe = ${JSON.stringify(recipe, null, 1)};\n` +
    `export const WORDS: Word[] = ${JSON.stringify(words)};\n`);
  const gens = check ? [] : readdirSync(join(ROOT, "src/tech/gen")).filter((f) => f.endsWith(".tech.gen.ts")).sort();
  wf(join(ROOT, "src/tech/registry.gen.ts"),
    `// generated by tools/tech_build.mjs; do not edit (lists src/tech/gen/*.tech.gen.ts)\nimport type { Word } from "../fin/recipe/types";\nimport type { TechRecipe } from "./types";\n` +
    gens.map((f, i) => `import * as T${i} from "./gen/${f.replace(/\.ts$/, "")}";`).join("\n") +
    `\n\nexport const TECH_RECIPES: { id: string; recipe: TechRecipe; words: Word[]; vo?: number }[] = [\n` +
    gens.map((_, i) => `  { id: T${i}.ID, recipe: T${i}.RECIPE, words: T${i}.WORDS, vo: T${i}.VO_DURATION },`).join("\n") + `\n];\n`);
  if (!check) console.log(`wrote src/tech/gen/${us}.tech.gen.ts and the tech registry (${gens.length} recipe(s)); composition ${pascal} ${LS ? "(1920x1080, no Sub)" : "(+Sub)"} in src/index.tech.ts`);

  // ---------------------------------------------------------------- 2) compile in node
  const stub = { name: "stub", setup(b) {
    b.onResolve({ filter: /^(remotion|@remotion\/.*|@react-three\/.*)$/ }, (a) => ({ path: a.path, namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "const P=new Proxy(function(){return P},{get:(t,k)=>k==='__esModule'?false:P,apply:()=>P,construct:()=>P}); module.exports=P;", loader: "js" }));
  } };
  const r = await build({ entryPoints: [join(ROOT, "tools/tech_entry.ts")], bundle: true, write: false, format: "esm", platform: "node", plugins: [stub], jsx: "automatic", logLevel: "error" });
  mkdirSync(join(ROOT, "out/tmp"), { recursive: true });
  const bundleF = join(ROOT, "out/tmp/tech_build.bundle.mjs");
  writeFileSync(bundleF, r.outputFiles[0].text);
  const m = await import(pathToFileURL(bundleF).href + "?" + Date.now());
  let C;
  const Tc = Date.now();
  try { C = m.compileTech(recipe, words, vo); } catch (e) { console.error(`COMPILE ERROR: ${e.message}`); return 1; }
  const compileS = (Date.now() - Tc) / 1000;
  const dur = C.duration / 30;
  writeFileSync(join(ROOT, `out/tmp/${slug}.cues.json`), JSON.stringify({ [pascal]: { music: C.audio.music, musicDb: -12, cues: C.audio.cues, duration: dur, cuts: C.shots.map((s) => s.a) } }));
  console.log(`compiled ${C.shots.length} shots, ${dur.toFixed(2)} s (${C.duration} frames), ${C.audio.cues.length} sfx cues`);
  if (noQa) return 0;

  // ---------------------------------------------------------------- 3) clip QA (Short: every frame x 4 sub-frames;
  // long-form: every Nth output frame, no sub-frames: it renders without motion blur)
  const ov = (p, a) => [0, 1, 2].every((k) => Math.abs(p.c[k] - a.c[k]) < p.h[k] + a.h[k]);
  const hits = new Map();
  const note = (k, t) => { if (!hits.has(k)) hits.set(k, t); };
  const Tq = Date.now();
  for (const t of qaTimes(C.duration, LS, qaSample)) {
    const { bolts, props } = C.qa(t);
    const sid = C.shotAt(t).id;
    for (const b of bolts) {
      if (b.c[1] - b.h[1] < -0.01) note(`${sid} ${b.name} below the ground`, t);
      for (const p of props) if (ov(p, b)) note(`${sid} ${p.name} x ${b.name}`, t);
    }
    const bodies = bolts.filter((b) => b.name.endsWith(".body"));
    for (let i = 0; i < bodies.length; i++) for (let j = i + 1; j < bodies.length; j++) if (ov(bodies[i], bodies[j])) note(`${sid} ${bodies[i].name} x ${bodies[j].name}`, t);
    for (const s of C.shotAt(t).props) {
      if (!s.def || !s.def.grounded || s.spec.motion === "path" || t < s.a || t >= s.b) continue;
      for (const p of props) if (p.name.startsWith(`${s.key}.`) && p.c[1] - p.h[1] < -0.05) note(`${sid} ${p.name} below the floor`, t);
    }
  }
  const qaLines = [...hits].map(([k, t]) => `CLIP ${k} first at ${t.toFixed(3)} s (frame ${Math.floor(t * 30)})`);
  const qaS = (Date.now() - Tq) / 1000;
  if (LS) return longForm({ m, C, recipe, words, slug, dir, pascal, check, wf, hits, qaLines, qaSample, qaS, compileS, T0 });

  // ---------------------------------------------------------------- 4) gate
  const sub3 = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
  const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
  const crs = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
  const nrm = (a) => { const l = Math.hypot(...a) || 1; return a.map((x) => x / l); };
  const coverage = (cam, b) => {
    const f = nrm(sub3(cam.look, cam.pos)), rgt = nrm(crs(f, [0, 1, 0])), up = crs(rgt, f), th = Math.tan((cam.fov * Math.PI) / 360), asp = 1080 / 1920;
    let y0 = Infinity, y1 = -Infinity, x0 = Infinity, x1 = -Infinity;
    for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) {
      const p = [b.c[0] + sx * b.h[0], b.c[1] + sy * b.h[1], b.c[2] + sz * b.h[2]];
      const d = sub3(p, cam.pos), z = dot(d, f);
      if (z <= 0.05) return 0;
      const ny = dot(d, up) / (z * th), nx = dot(d, rgt) / (z * th * asp);
      y0 = Math.min(y0, ny); y1 = Math.max(y1, ny); x0 = Math.min(x0, nx); x1 = Math.max(x1, nx);
    }
    if (x1 < -1 || x0 > 1) return 0;
    return Math.max(0, Math.min(1, y1) - Math.max(-1, y0)) / 2;
  };
  const cam0 = C.camAt(0);
  const subjects = [];
  for (const st of C.boltsAt(0)) subjects.push({ name: st.id, bolt: true, c: [st.x, st.y + 0.12 * st.s, st.z], h: [0.4 * st.s, 0.45 * st.s, 0.35 * st.s] });
  for (const p of C.shotAt(0).props) if (p.def) { const b = m.objBox(p.def, C.placeOf(p, 0)); subjects.push({ name: p.key, c: b.c, h: b.h }); }
  const covs = subjects.map((b) => ({ name: b.name, bolt: !!b.bolt, k: coverage(cam0, b) })).sort((a, b) => b.k - a.k);
  const best = covs[0] ?? { name: "nothing", k: 0 };
  const hookText = recipe.hook.text;
  const hookWords = hookText.replace(/\*/g, "").trim().split(/\s+/).length;
  const hookLines = m.hookLines(hookText);
  const orange = (hookText.match(/\*[^*]+\*/g) ?? []);
  const hookW = Math.max(...hookLines.map((l) => l.replace(/\*/g, "").length * 0.63 * m.HOOK_FS + 80));
  const Q = /\?|^(how|why|what|where|when|who|which)\b|\d/i;
  let stakeAt = null;
  for (let f = 0; f <= 15 && stakeAt === null; f++) if (C.textsAt(f / 30).some((s) => Q.test(s))) stakeAt = f / 30;
  const face0 = new Map(C.boltsAt(0).map((b) => [b.id, b.face]));
  let faceAt = null;
  for (let f = 1; f <= 45 && faceAt === null; f++) for (const b of C.boltsAt(f / 30)) if (!face0.has(b.id) || face0.get(b.id) !== b.face) { faceAt = f / 30; break; }
  const PUNCH = /^(impact|drop|crash|boom|thud|punch|stamp|coins|scratch|paper|rip)/;
  const sfx0 = C.audio.cues.filter((c) => c.t <= 0.02);
  const moves = new Set();
  for (const s of C.shots) { if (s.a > 0 && s.a <= 3.0) moves.add(`cut ${s.a.toFixed(2)}`); for (const [t] of s.kicks) if (t <= 3.0 && t > 0.05) moves.add(`hit ${t.toFixed(2)}`); }
  const early = C.shots.filter((s) => s.a < 1.0);
  const whoAt0 = covs.filter((c) => c.bolt && c.k >= 0.15), whatAt0 = covs.filter((c) => !c.bolt && c.k >= 0.04);
  // caption band: BOLT's screen face must stay out of y 1239-1449 (centre 1344 +- 105) while captions show
  const band = [m.CAP_CENTRE - 105, m.CAP_CENTRE + 105];
  let capT = 0, capOk = 0;
  const capBad = new Set(), labelFace = new Set(), labelBand = new Set(), staticF = [];
  const faceRect = (cam, st) => { const f = m.boltFace(st); const q = m.project(cam, f.c); if (!q || q.x < -100 || q.x > 1180) return null; const r = f.r * q.k; return { x: q.x, y: q.y, w: 2 * r, h: 2 * r }; };
  const hitR = (a, b) => Math.abs(a.x - b.x) * 2 < a.w + b.w && Math.abs(a.y - b.y) * 2 < a.h + b.h;
  const hookN = hookLines.length, hookBox = { x: 540, y: m.HOOK_TOP + (hookN * m.HOOK_FS * 1.04 + 52) / 2, w: hookW + 80, h: hookN * m.HOOK_FS * 1.04 + 52 };
  const hookFace = new Set(), labelBoard = new Set();
  let prevCam = null;
  for (let f = 0; f < C.duration; f++) {
    const t = f / 30, s = C.shotAt(t), cam = C.camAt(t);
    if (prevCam && C.shotAt((f - 1) / 30) === s) {
      const d = Math.hypot(...sub3(cam.pos, prevCam.pos)) + Math.hypot(...sub3(cam.look, prevCam.look)) + Math.abs(cam.fov - prevCam.fov) * 0.01 + Math.abs((cam.roll ?? 0) - (prevCam.roll ?? 0)) * 0.01;
      if (d < 2e-4) staticF.push(f);
    }
    prevCam = cam;
    const faces = C.boltsAt(t).map((st) => faceRect(cam, st)).filter(Boolean);
    const capOn = t >= 1.0 && recipe.captions !== "off" && s.spec.caption !== "off";
    if (capOn) { capT++; if (faces.every((r) => r.y + r.h / 2 < band[0] || r.y - r.h / 2 > band[1])) capOk++; else capBad.add(s.id); }
    for (const l of C.labelsAt(t)) {
      if (l.u < 0.3) continue;
      if (faces.some((r) => hitR(l, r))) labelFace.add(`${l.text}@${t.toFixed(1)}s`);
      if (l.y + l.h / 2 > band[0] - 1) labelBand.add(l.text);
    }
    const bds = C.boardsAt(t).filter((b) => b.u >= 0.3);
    for (const b of bds) if (faces.some((r) => hitR(b, r))) labelFace.add(`board ${b.title}@${t.toFixed(1)}s`);
    for (const l of C.labelsAt(t)) if (l.u >= 0.3) for (const b of bds) if (hitR(l, b)) labelBoard.add(`${l.text}/${b.title}@${t.toFixed(1)}s`);
    if (t <= C.hookUntil || (C.hookAgain !== null && t >= C.hookAgain)) for (const r of faces) if (hitR(hookBox, r)) hookFace.add(`${s.id}@${t.toFixed(1)}s`);
  }
  const capShare = capT ? capOk / capT : 1;
  const oneAtATime = [];
  for (const s of C.shots) { const ts = s.labels.map((l) => l.t0).sort((a, b) => a - b); for (let i = 1; i < ts.length; i++) if (ts[i] - ts[i - 1] < 0.3) oneAtATime.push(`${s.id} ${ts[i - 1].toFixed(2)}/${ts[i].toFixed(2)} s`); }
  const nLabels = C.shots.reduce((n, s) => n + s.labels.length, 0);
  const firstCut = C.shots.length > 1 ? C.shots[1].a : dur;
  const lastShot = C.shots[C.shots.length - 1], firstShot = C.shots[0];
  const loopy = C.hookAgain !== null && JSON.stringify(lastShot.spec.cam.target) === JSON.stringify(firstShot.spec.cam.target);
  const fmt = recipe.format ?? "short";
  const lenOk = fmt === "long" ? dur >= 300 && dur <= 480 : dur >= 30 && dur <= 55;
  // framing QA (screen space, tools/framing_qa.mjs + framing_kits.mjs): heads vs boards/cards, the subject in frame,
  // cards inside the frame, text contrast and size, frame-0 face (RECIPE_GUIDE.md "Framing rules", KIT_*.md)
  const KF = runFraming("tech3d", C, m, recipe);
  const gate = [
    ["frame 0 is close: a subject covers >= 50 % of the frame height", best.k >= 0.5, `${best.name} ${(best.k * 100).toFixed(0)} %`, true],
    ["hook at frame 0: <= 5 words, <= 2 lines that fit, exactly one *orange* word", C.hookUntil > 0 && hookWords <= 5 && hookLines.length <= 2 && hookW <= 980 && orange.length === 1, `"${hookText}" (${hookWords} words, ${hookLines.length} line(s), widest ~${hookW.toFixed(0)} px, orange: ${orange.join(" ") || "none"}, until ${C.hookUntil.toFixed(2)} s)`, true],
    ["who + what at frame 0 (BOLT >= 15 % and an object in view)", whoAt0.length > 0 && whatAt0.length > 0, `who: ${whoAt0.map((c) => c.name).join(", ") || "none"}; what: ${whatAt0.map((c) => c.name).join(", ") || "none"}`, true],
    ["the question (how/why/what... or a number) on screen by 0.5 s", stakeAt !== null, stakeAt === null ? "none by 0.5 s" : `at ${stakeAt.toFixed(2)} s`, true],
    ["first spoken word by 0.2 s", words[0].t <= 0.2, `${words[0].w} at ${words[0].t.toFixed(2)} s`, true],
    ["a sound punch at 0.00 s", sfx0.some((c) => PUNCH.test(c.sfx)), sfx0.map((c) => c.sfx).join(", ") || "none", true],
    ["2-3 cuts or big moves in the first 3 s", moves.size >= 2, [...moves].join(", ") || "none", true],
    ["music + an SFX at frame 0", !!C.audio.music && C.audio.cues.some((c) => c.t <= 0.05), `${C.audio.music}, ${C.audio.cues.filter((c) => c.t <= 0.05).map((c) => c.sfx).join(", ")}`, true],
    ["BOLT's face changes by 1.5 s", faceAt !== null, faceAt === null ? "no face change by 1.5 s" : `at ${faceAt.toFixed(2)} s`, true],
    ["no wide shot in the first 1 s", early.every((s) => s.spec.cam.preset !== "wide"), early.map((s) => `${s.id} ${s.spec.cam.preset}`).join(", "), true],
    ["frame-0 shot cuts away by ~1.0 s (first cut <= 1.25 s)", firstCut <= 1.25, `first cut at ${firstCut.toFixed(2)} s`, true],
    ["BOLT's face clear of the caption band on >= 90 % of caption time", capShare >= 0.9, `${(capShare * 100).toFixed(0)} %${capBad.size ? `; face in the band in ${[...capBad].join(", ")}` : ""}`, true],
    ["labels: <= 3 words each (compile-enforced), popping in one at a time (>= 0.3 s apart)", oneAtATime.length === 0, `${nLabels} label(s)${oneAtATime.length ? `; too close: ${oneAtATime.join(", ")}` : ""}`, true],
    ["text off faces: no label card or board over BOLT's screen face", labelFace.size === 0, [...labelFace].slice(0, 6).join(", ") || "none", true],
    ["the hook card never covers BOLT's screen face", hookFace.size === 0, [...hookFace].slice(0, 6).join(", ") || "clear", true],
    ["label cards never overlap a board", labelBoard.size === 0, [...labelBoard].slice(0, 6).join(", ") || "none", true],
    ["label cards above the caption band", labelBand.size === 0, [...labelBand].join(", ") || "all above", true],
    ["no static frames: the camera moves on every frame", staticF.length === 0, staticF.length ? `${staticF.length} still frame(s), first ${staticF.slice(0, 5).join(", ")}` : "moves on every frame", true],
    ["loop ending: the hook comes back and the last shot frames the first shot's subject", loopy, `hook again ${C.hookAgain === null ? "not set" : `at ${C.hookAgain.toFixed(2)} s`}; last target ${JSON.stringify(lastShot.spec.cam.target)}`, false],
    [fmt === "long" ? "length 5-8 min" : "length 30-55 s", lenOk, `${dur.toFixed(2)} s`, false],
  ];
  gate.push(...KF.rows);
  const hardFail = gate.some((g) => g[3] && !g[1]);
  const rep = [
    `# ${slug}: tech3d recipe QA (tools/tech_build.mjs)`, "",
    `Composition: \`${pascal}\` (+ \`${pascal}Sub\`) in \`src/index.tech.ts\`. Kit tech3d, format ${fmt}. ${C.shots.length} shots, ${dur.toFixed(2)} s.`, "",
    `## Clip QA: ${C.duration} frames x 4 sub-frames, ${hits.size} clip(s)`, "",
    ...(qaLines.length ? qaLines.map((l) => `- ${l}`) : ["- none: no part, kit prop or set piece enters BOLT's shell or mitts; BOLT stays above the ground; grounded objects stay above the floor."]), "",
    ...KF.fr.md,
    `## Frame-0 gate and kit rules`, "", "| check | result | detail |", "|---|---|---|",
    ...gate.map(([k, ok, d, hard]) => `| ${k} | ${ok ? "PASS" : hard ? "**FAIL**" : "warn"} | ${d} |`), "",
    `Frame-0 coverage by subject: ${covs.slice(0, 5).map((c) => `${c.name} ${(c.k * 100).toFixed(0)} %`).join(", ")}.`, "",
  ];
  wf(join(dir, "RECIPE_QA.md"), rep.join("\n"));
  console.log(`clip QA: ${hits.size} clip(s)`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}`);
  return hits.size || hardFail ? 1 : 0;
};

// ---------------------------------------------------------------- LONG-FORM (format "landscape"): the shared gate
const longForm = ({ m, C, recipe, words, slug, dir, pascal, check, wf, hits, qaLines, qaSample, qaS, compileS, T0 }) => {
  const Tg = Date.now();
  const dur = C.duration / 30;
  const W = 1920, H = 1080, BAND = [905 - 72, 905 + 72]; // LF.CAP_Y +- LF.CAP_HALF
  // caption share: the fraction of caption time whose lower-third centre is >= 75 % of the height
  let capT = 0, capOk = 0;
  const moved = new Set();
  const small = new Set(), edge = new Set(), band = new Set();
  const M = 0.015;
  const boxNote = (kind, b, t) => {
    const x0 = b.x - b.w / 2, x1 = b.x + b.w / 2, y0 = b.y - b.h / 2, y1 = b.y + b.h / 2;
    if (x0 < W * M || x1 > W * (1 - M) || y0 < H * M || y1 > H * (1 - M)) edge.add(`${kind} at ${t.toFixed(1)} s [${x0.toFixed(0)},${y0.toFixed(0)}-${x1.toFixed(0)},${y1.toFixed(0)}]`);
    if (y1 > BAND[0] && y0 < BAND[1]) band.add(`${kind}`);
  };
  // glyph heights at 1080p: label cards 54 px type, boards 40 px title / 118 px value (cap height ~0.7 em)
  if (m.LABEL_FS * 0.7 < 30) small.add(`label type ${m.LABEL_FS} px`);
  for (let f = 0; f < C.duration; f += qaSample) {
    const t = f / 30, s = C.shotAt(t);
    const capOn = t >= 1.0 && recipe.captions !== "off" && s.spec.caption !== "off";
    if (capOn) { capT++; const y = C.capY(s); if (y >= 0.75 * H) capOk++; if (y !== 905) moved.add(`${s.id} ${y.toFixed(0)}`); }
    for (const l of C.labelsAt(t)) if (l.u >= 0.95) boxNote(`label ${l.text}`, l, t);
    for (const b of C.boardsAt(t)) if (b.u >= 0.95) boxNote(`board ${b.title}`, b, t);
  }
  const shots = C.shots.map((s) => ({ id: s.id, a: s.a, b: s.b, set: s.set, beat: !!s.spec.beat }));
  const { gate, pacing } = kitLongGate({
    shots, events: C.events(), chapters: C.chapters, words, dur, audio: C.audio, hookUntil: C.hookUntil, hookText: recipe.hook.text.replace(/\*/g, ""),
    caps: { share: capT ? capOk / capT : 1, moved: [...moved] }, boards: { small: [...small], edge: [...edge], band: [...band] },
  });
  const gateS = (Date.now() - Tg) / 1000;
  const KFL = runFraming("tech3d", C, m, recipe, true, qaSample);
  gate.push(...KFL.rows);
  const chTxt = chaptersTxt(C.chapters);
  const rep = kitLongReport({ framingMd: KFL.fr.md, slug, kit: "tech3d", tool: "tech_build.mjs", entry: "src/index.tech.ts", pascal, C, dur, words, chapters: C.chapters, hits, qaLines, qaSample, qaS, gate, gateS, pacing, chTxt,
    extra: [`Layout: hook top-centre at ${C.layout.HOOK_TOP} px (${C.layout.HOOK_FS} px type), cards between y ${C.layout.SAFE_TOP}-${C.layout.SAFE_BOTTOM} (below ${C.layout.SAFE_TOP_HOOK} while the hook shows), lower-third captions centred at 905 px unless BOLT's face sits in the band.`, ""] });
  wf(join(dir, "RECIPE_QA.md"), rep.join("\n"));
  wf(join(dir, "chapters.txt"), chTxt);
  console.log(`clip QA: ${hits.size} clip(s) over ${Math.ceil(C.duration / qaSample)} of ${C.duration} frames (every ${qaSample === 1 ? "frame" : `${qaSample}th frame`})`);
  for (const l of qaLines.slice(0, 40)) console.log("  " + l);
  for (const [k, ok, d, hard] of gate) console.log(`${ok ? "PASS" : hard ? "FAIL" : "warn"}  ${k}: ${d}`);
  console.log(`timings: compile ${compileS.toFixed(2)} s, clip QA ${qaS.toFixed(2)} s, gate ${gateS.toFixed(2)} s, total ${((Date.now() - T0) / 1000).toFixed(2)} s`);
  if (!check) console.log(`report: ${join(dir, "RECIPE_QA.md")}; chapters: ${join(dir, "chapters.txt")}`);
  return hits.size || gate.some((g) => g[3] && !g[1]) ? 1 : 0;
};

